    bl.serr([204, 141.6], 7, 2.9, [0, -1]);
    const e2 = bl.mark();
    bl.l([[196, 141.6], [186, 136], [181, 120]]).z();
    const spine = bl.pl.slice(s0, s1 + 1), edge = bl.pl.slice(s1, e2 + 1);
