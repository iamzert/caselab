    const bl = P();
    bl.l([[181, 82], [190, 74]]);
    const s0 = bl.mark();
    bl.c([[190, 74], [206, 68.8], [222, 69.6], [245, 75.4], [290, 79.8], [340, 79.6], [390, 75.6], [440, 67.6], [475, 60.4], [505, 54]]);
    const s1 = bl.mark();
    bl.c([[505, 54], [490, 63.4], [470, 76.6], [445, 92], [420, 105.4], [395, 116.4], [370, 125.2], [345, 131.6], [320, 136.2], [300, 139]]);
