  const r1 = (v) => Math.round(v * 10) / 10;
  const pt = (p) => r1(p[0]) + ',' + r1(p[1]);
  const lerp = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
  function bz(s, t) {
    const u = 1 - t;
    return [u * u * u * s[0][0] + 3 * u * u * t * s[1][0] + 3 * u * t * t * s[2][0] + t * t * t * s[3][0],
      u * u * u * s[0][1] + 3 * u * u * t * s[1][1] + 3 * u * t * t * s[2][1] + t * t * t * s[3][1]];
  }
  // Сглаженная кривая через точки (Катмулл–Ром, k — натяжение) → кубические сегменты
  function crSegs(pts, k) {
    k = k == null ? 1 : k;
    const out = [];
    for (let i = 0; i < pts.length - 1; i++) {
      const a = pts[i - 1] || pts[i], b = pts[i], c = pts[i + 1], e = pts[i + 2] || pts[i + 1];
      out.push([b, [b[0] + (c[0] - a[0]) * k / 6, b[1] + (c[1] - a[1]) * k / 6], [c[0] - (e[0] - b[0]) * k / 6, c[1] - (e[1] - b[1]) * k / 6], c]);
    }
    return out;
  }
  // Контур: d — строка SVG-пути, pl — плотная ломаная по тому же контуру (для полос, смещений и насечек)
  function Shape(p0) {
    const o = { d: 'M' + pt(p0), pl: [p0] };
    const last = () => o.pl[o.pl.length - 1];
    o.L = function () { for (let i = 0; i < arguments.length; i++) { o.d += ' L' + pt(arguments[i]); o.pl.push(arguments[i]); } return o; };
    o.S = function (pts, k) {                     // плавно через точки
      crSegs([last()].concat(pts), k).forEach((s) => {
        o.d += ' C' + pt(s[1]) + ' ' + pt(s[2]) + ' ' + pt(s[3]);
        for (let j = 1; j <= 10; j++) o.pl.push(bz(s, j / 10));
      });
      return o;
    };
    o.C = function (c1, c2, p) {
      const s = [last(), c1, c2, p];
      o.d += ' C' + pt(c1) + ' ' + pt(c2) + ' ' + pt(p);
      for (let j = 1; j <= 10; j++) o.pl.push(bz(s, j / 10));
      return o;
    };
    o.Q = function (c, p) {
      const a = last();
      return o.C(lerp(a, c, 2 / 3), lerp(p, c, 2 / 3), p);
    };
    o.i = () => o.pl.length - 1;                  // метка: индекс текущей точки
    o.Z = () => { o.d += ' Z '; return o; };
    return o;
  }
  // Длины вдоль ломаной, точка на доле длины, кусок между долями
  function lens(pl) {
    const L = [0];
    for (let i = 1; i < pl.length; i++) L.push(L[i - 1] + Math.hypot(pl[i][0] - pl[i - 1][0], pl[i][1] - pl[i - 1][1]));
    return L;
  }
  function at(pl, t) {
    const L = lens(pl), s = t * L[L.length - 1];
    let i = 1;
    while (i < L.length - 1 && L[i] < s) i++;
    return lerp(pl[i - 1], pl[i], Math.max(0, Math.min(1, (s - L[i - 1]) / ((L[i] - L[i - 1]) || 1))));
  }
  // Смещение ломаной по нормали на f(t) (t — доля длины); «+» — влево по ходу (для хода вправо — вверх)
  function offs(pl, f) {
    const L = lens(pl), tot = L[L.length - 1] || 1, n = pl.length;
    return pl.map((p, i) => {
      const a = pl[Math.max(0, i - 1)], b = pl[Math.min(n - 1, i + 1)];
      const nx = b[1] - a[1], ny = a[0] - b[0], l = Math.hypot(nx, ny) || 1;
      const d = typeof f === 'function' ? f(L[i] / tot) : f;
      return [p[0] + nx / l * d, p[1] + ny / l * d];
    });
  }
