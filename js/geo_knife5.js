    const pm = Shape([76, top(76)]).L([44, 80.2]).C([35.4, 80.4], [30, 84.2], [29.4, 90.2]).L([28.8, 105.6])
      .C([29.4, 111.6], [34.2, 115.4], [43, 115.6]).L([76, bot(76)]).Z();
    P.push(['p', pm.d + circ(45, 97.8, 5.2)]);
