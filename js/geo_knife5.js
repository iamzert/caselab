    const sp = prof([[226, 75], [250, 74], [266, 72.6], [284, 71.1], [300, 70.6], [340, 70.8], [394, 71.2]]);
    function spine() {
      const s = Shape([230, sp(230)]).L([262, sp(262)]);
      for (let x = 266; x < 298; x += 3.2) s.L([x, sp(x)], [x + 1.1, sp(x + 1.1) + 1.5], [x + 2.2, sp(x + 2.2)]);
      return s.L([394, 71.2]);
    }
    // упор под палец (общий для силуэта и плоскости)
    const LUG = [[273.4, 124.8], [268.6, 129.6], [264.2, 134.6], [259.6, 137.2], [255.2, 136.2], [251.6, 132.8],
      [248.4, 127.6], [244.6, 123], [238, 120.2]];
