  // (одна и та же ломаная служит и заливкой накладки, и границей для насечки)
  function smooth(pts, k, n) {
    const out = [], L = pts.length;
    for (let i = 0; i < L; i++) {
      const a = pts[(i - 1 + L) % L], b = pts[i], c = pts[(i + 1) % L], e = pts[(i + 2) % L];
      const c1 = [b[0] + (c[0] - a[0]) * k / 6, b[1] + (c[1] - a[1]) * k / 6], c2 = [c[0] - (e[0] - b[0]) * k / 6, c[1] - (e[1] - b[1]) * k / 6];
      for (let j = 0; j < n; j++) {
        const t = j / n, u = 1 - t;
        out.push([u * u * u * b[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t * t * t * c[0],
          u * u * u * b[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t * t * t * c[1]]);
      }
    }
    return out;
  }
