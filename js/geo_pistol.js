        const ok = [[0, 0], [pad, 0], [-pad, 0], [0, len / 2 + pad], [0, -len / 2 - pad]].every((o) => inside(pg, x + o[0], y + o[1]));
        if (ok) d += 'M' + pt([x, y - len / 2]) + ' L' + pt([x, y + len / 2]) + ' ';
