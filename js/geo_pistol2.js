  // Штриховка выпуклого многоугольника poly ([[x, y], ...]) линиями под углом deg с шагом step
  function hatch(poly, deg, step) {
    const a = deg * Math.PI / 180, dx = Math.cos(a), dy = Math.sin(a), nx = -dy, ny = dx;
    let lo = 1e9, hi = -1e9;
    poly.forEach((p) => { const t = p[0] * nx + p[1] * ny; lo = Math.min(lo, t); hi = Math.max(hi, t); });
    let d = '';
    for (let t = lo + step * 0.5; t < hi; t += step) {
      const pts = [];
      poly.forEach((p, i) => {
        const q = poly[(i + 1) % poly.length];
        const ta = p[0] * nx + p[1] * ny - t, tb = q[0] * nx + q[1] * ny - t;
        if ((ta < 0) !== (tb < 0)) { const k = ta / (ta - tb); pts.push([p[0] + (q[0] - p[0]) * k, p[1] + (q[1] - p[1]) * k]); }
      });
      if (pts.length < 2) continue;
      pts.sort((u, v) => (u[0] * dx + u[1] * dy) - (v[0] * dx + v[1] * dy));
      const A = pts[0], B = pts[pts.length - 1];
      d += 'M' + F(A[0]) + ',' + F(A[1]) + ' L' + F(B[0]) + ',' + F(B[1]) + ' ';
    }
    return d;
  }
