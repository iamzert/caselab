    d += F` L${x1 - 0.8},${y} Q${x1},${y} ${x1},${y + 0.8} L${x1},${y + h} Z`;
    return [['m', d], ['d', F`M${x0 + 0.8},${y + h - 1.1} L${x1 - 0.8},${y + h - 1.1}`, 0.6]];
