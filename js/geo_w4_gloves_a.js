'use strict';

// Перчатки по рендерам CS2 (референсы пользователя tools/refs/73–84.png): glsp (спортивные), gldr (водительские).
// Пара рисуется в поле 512×192; готовая картинка отражается по горизонтали (как всё оружие в игре).
// Загружается после js/geo_gloves*.js: GEO.<id> здесь заменяет прежнюю модель.
//
// Обе перчатки пары нарисованы явно одним списком деталей (дальняя повёрнута к нам ладонью, поэтому она не копия
// ближней): сначала дальняя (роль q — темнее), потом ближняя. Координаты пишутся «как на картинке CS2» — в системе
// вырезки референса 380×250 (ближняя перчатка слева, пальцы вниз-вправо); tp() переводит их в поле 512×192
// с зеркалом по x, а игра отражает картинку обратно — в карточке пара лежит как на рендере CS2.
// Скин ложится на ткань и основные панели (p/q); ладонь, кончики пальцев, манжета, ремешок — свой материал ('…!').
(function () {
  const f1 = (v) => Math.round(v * 10) / 10;
  const pt = (p) => f1(p[0]) + ',' + f1(p[1]);

  // ---------- Перевод координат референса в поле ----------
  const K = 0.73, OX = 113, OY = 3;
  const X = (u) => f1(512 - OX - K * u), Y = (v) => f1(OY + K * v);
  function tp(d) {
    let out = '';
    const re = /([MLCQSTAHVZ])([^MLCQSTAHVZ]*)/g;
    let m;
    while ((m = re.exec(d))) {
      const c = m[1], n = (m[2].match(/-?\d*\.?\d+/g) || []).map(Number);
      if (c === 'Z') { out += ' Z'; continue; }
      if (c === 'H') { out += ' H' + n.map(X).join(' '); continue; }
      if (c === 'V') { out += ' V' + n.map(Y).join(' '); continue; }
      if (c === 'A') {
        for (let i = 0; i + 6 < n.length; i += 7) {
          out += ' A' + f1(n[i] * K) + ',' + f1(n[i + 1] * K) + ' ' + (-n[i + 2]) + ' ' + n[i + 3] + ',' + (1 - n[i + 4]) + ' ' + X(n[i + 5]) + ',' + Y(n[i + 6]);
        }
        continue;
      }
      out += ' ' + c;
      for (let i = 0; i + 1 < n.length; i += 2) out += (i ? ' ' : '') + X(n[i]) + ',' + Y(n[i + 1]);
    }
    return out.trim();
  }

  // ---------- Список деталей ----------
  let P = [];
  const F = (r, d, mat) => { P.push(mat ? [r, tp(d), mat] : [r, tp(d)]); };   // заливка p/q/m/l/k
  const Ln = (r, d, w) => { P.push(w != null ? [r, tp(d), w] : [r, tp(d)]); };  // линия d/h/s/e
  const O = (u, v, r) => { P.push(['o', X(u), Y(v), f1(r * K)]); };              // заклёпка, кнопка

  // ---------- Кривые ----------
  // Гладкая кривая через точки (Катмулл — Ром → кубические Безье); текущая точка — pts[0]
  function cr(pts) {
    let d = '';
    for (let i = 0; i < pts.length - 1; i++) {
      const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
      d += ' C' + pt([p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6]) + ' ' +
        pt([p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6]) + ' ' + pt(p2);
    }
    return d;
  }
  const curve = (pts) => 'M' + pt(pts[0]) + cr(pts);
  // Замкнутый контур из гладких участков (каждый начинается там, где кончился предыдущий); на стыках — изломы
  function shape() {
    const runs = Array.prototype.slice.call(arguments);
    let d = 'M' + pt(runs[0][0]);
    runs.forEach((r) => { d += cr(r); });
    return d + ' Z';
  }
  // Гладкий замкнутый контур без изломов
  function loop(pts) {
    const n = pts.length;
    let d = 'M' + pt(pts[0]);
    for (let i = 0; i < n; i++) {
      const p0 = pts[(i + n - 1) % n], p1 = pts[i], p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
      d += ' C' + pt([p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6]) + ' ' +
        pt([p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6]) + ' ' + pt(p2);
    }
    return d + ' Z';
  }
  // Повёрнутый эллипс и прямоугольник со скруглёнными углами (ang — радианы)
  function ell(cx, cy, rx, ry, ang) {
    const c = Math.cos(ang || 0), s = Math.sin(ang || 0), k = 0.5523;
    const T = (x, y) => [cx + x * c - y * s, cy + x * s + y * c];
    const p = [T(rx, 0), T(0, ry), T(-rx, 0), T(0, -ry)];
    const q = [[T(rx, ry * k), T(rx * k, ry)], [T(-rx * k, ry), T(-rx, ry * k)], [T(-rx, -ry * k), T(-rx * k, -ry)], [T(rx * k, -ry), T(rx, -ry * k)]];
    let d = 'M' + pt(p[0]);
    for (let i = 0; i < 4; i++) d += ' C' + pt(q[i][0]) + ' ' + pt(q[i][1]) + ' ' + pt(p[(i + 1) % 4]);
    return d + ' Z';
  }
  function rrect(cx, cy, w, h, r, ang) {
    const c = Math.cos(ang || 0), s = Math.sin(ang || 0), k = 0.448;
    const T = (x, y) => pt([cx + x * c - y * s, cy + x * s + y * c]);
    const x0 = -w / 2, x1 = w / 2, y0 = -h / 2, y1 = h / 2;
    return 'M' + T(x0 + r, y0) + ' L' + T(x1 - r, y0) + ' C' + T(x1 - r * k, y0) + ' ' + T(x1, y0 + r * k) + ' ' + T(x1, y0 + r) +
      ' L' + T(x1, y1 - r) + ' C' + T(x1, y1 - r * k) + ' ' + T(x1 - r * k, y1) + ' ' + T(x1 - r, y1) +
      ' L' + T(x0 + r, y1) + ' C' + T(x0 + r * k, y1) + ' ' + T(x0, y1 - r * k) + ' ' + T(x0, y1 - r) +
      ' L' + T(x0, y0 + r) + ' C' + T(x0, y0 + r * k) + ' ' + T(x0 + r * k, y0) + ' ' + T(x0 + r, y0) + ' Z';
  }
  // Точки-перфорация: короткие штрихи с круглыми концами (роль d)
  const dots = (list) => list.map((p) => 'M' + pt(p) + ' L' + pt([p[0] + 0.5, p[1] + 0.2])).join(' ');

  // ---------- Пальцы ----------
  // Ось пальца — квадратичная кривая от основания b к кончику t; bend — прогиб середины по нормали (к верхнему краю)
  // prof === false — ровная трубка (рёбра, валики); иначе палец чуть уже на суставах
  function fing(b, t, w0, w1, bend, prof) {
    const dx = t[0] - b[0], dy = t[1] - b[1], l = Math.hypot(dx, dy);
    return { b: b, t: t, c: [(b[0] + t[0]) / 2 + dy / l * bend, (b[1] + t[1]) / 2 - dx / l * bend], w0: w0, w1: w1, prof: prof !== false };
  }
  function at(f, s) {
    const u = 1 - s;
    return [u * u * f.b[0] + 2 * u * s * f.c[0] + s * s * f.t[0], u * u * f.b[1] + 2 * u * s * f.c[1] + s * s * f.t[1]];
  }
  function tg(f, s) {
    const x = 2 * (1 - s) * (f.c[0] - f.b[0]) + 2 * s * (f.t[0] - f.c[0]), y = 2 * (1 - s) * (f.c[1] - f.b[1]) + 2 * s * (f.t[1] - f.c[1]);
    const l = Math.hypot(x, y) || 1;
    return [x / l, y / l];
  }
  // точка на оси со смещением o по нормали (o > 0 — к верхнему краю пальца)
  function off(f, s, o) { const p = at(f, s), k = tg(f, s); return [p[0] + k[1] * o, p[1] - k[0] * o]; }
  const waist = (s) => 1 - 0.05 * (Math.exp(-Math.pow((s - 0.45) / 0.07, 2)) + Math.exp(-Math.pow((s - 0.7) / 0.06, 2)));
  const wid = (f, s) => (f.w0 + (f.w1 - f.w0) * s) * (f.prof ? waist(s) : 1);
  // Трубка вдоль оси от s0 до s1, ширина — доля kw ширины пальца; tip / base — скругление концов (0 — прямой срез)
  function tube(f, s0, s1, kw0, kw1, tip, base) {
    const N = 10, A = [], B = [];
    for (let i = 0; i <= N; i++) {
      const s = s0 + (s1 - s0) * i / N, w = wid(f, s) * (kw0 + (kw1 - kw0) * i / N) / 2;
      A.push(off(f, s, w)); B.push(off(f, s, -w));
    }
    let d = 'M' + pt(A[0]) + cr(A);
    const t1 = tg(f, s1), r1 = 1.333 * (tip || 0) * wid(f, s1) * kw1 / 2;
    d += ' C' + pt([A[N][0] + t1[0] * r1, A[N][1] + t1[1] * r1]) + ' ' + pt([B[N][0] + t1[0] * r1, B[N][1] + t1[1] * r1]) + ' ' + pt(B[N]);
    B.reverse();
    d += cr(B);
    if (base) {
      const t0 = tg(f, s0), r0 = 1.333 * base * wid(f, s0) * kw0 / 2;
      d += ' C' + pt([B[N][0] - t0[0] * r0, B[N][1] - t0[1] * r0]) + ' ' + pt([A[0][0] - t0[0] * r0, A[0][1] - t0[1] * r0]) + ' ' + pt(A[0]);
    }
    return d + ' Z';
  }
  // Поперечная складка / шов на s (kw — доля ширины, bow — выгиб к кончику)
  function across(f, s, kw, bow) {
    const w = wid(f, s) * kw / 2, p = off(f, s, w), q = off(f, s, -w), m = at(f, s), k = tg(f, s);
    return 'M' + pt(p) + ' Q' + pt([m[0] + k[0] * bow * 2, m[1] + k[1] * bow * 2]) + ' ' + pt(q);
  }
  // Линия вдоль пальца: смещение — доля полуширины (k0 → k1)
  function along(f, s0, s1, k0, k1) {
    const pts = [];
    for (let i = 0; i <= 6; i++) { const s = s0 + (s1 - s0) * i / 6; pts.push(off(f, s, wid(f, s) / 2 * (k0 + (k1 - k0) * i / 6))); }
    return curve(pts);
  }
  // Точки контура над основаниями пальцев (сверху вниз): плавный шов по костяшкам — верхний угол первого пальца,
  // точки чуть дальше оснований, нижний угол последнего
  function knuckles(fs, depth) {
    const pts = [], corner = (f, sg) => {
      const k = tg(f, 0), h = f.w0 / 2 - 0.5;
      return [f.b[0] + k[1] * h * sg + k[0] * 3, f.b[1] - k[0] * h * sg + k[1] * 3];
    };
    pts.push(corner(fs[0], 1));
    fs.forEach((f) => { const k = tg(f, 0); pts.push([f.b[0] + k[0] * depth, f.b[1] + k[1] * depth]); });
    pts.push(corner(fs[fs.length - 1], -1));
    return pts;
  }
  // Точка «перед основанием пальца» (к запястью) — для краёв накладок
  const behind = (f, d, o) => { const k = tg(f, 0); return [f.b[0] - k[0] * d + k[1] * (o || 0), f.b[1] - k[1] * d - k[0] * (o || 0)]; };

  // Эмблема-кубик (логотип игры): шестиугольник светлого металла и три ребра
  function cube(cx, cy, r) {
    const p = [];
    for (let i = 0; i < 6; i++) { const a = Math.PI / 6 + i * Math.PI / 3; p.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]); }
    F('l', 'M' + p.map(pt).join(' L') + ' Z');
    Ln('d', 'M' + pt([cx, cy]) + ' L' + pt(p[1]) + ' M' + pt([cx, cy]) + ' L' + pt(p[3]) + ' M' + pt([cx, cy]) + ' L' + pt(p[5]), 0.8);
  }
  // Полоса вдоль пальца между смещениями k0..k1 (доли полуширины, «+» — к верхнему краю); r — скругление концов
  function strip(f, s0, s1, k0, k1, r) {
    const N = 10, A = [], B = [];
    for (let i = 0; i <= N; i++) {
      const s = s0 + (s1 - s0) * i / N, h = wid(f, s) / 2;
      A.push(off(f, s, h * k1)); B.push(off(f, s, h * k0));
    }
    const e = (s) => 1.333 * (r || 0) * wid(f, s) * Math.abs(k1 - k0) / 4;
    const t1 = tg(f, s1), e1 = e(s1), t0 = tg(f, s0), e0 = e(s0);
    let d = 'M' + pt(A[0]) + cr(A);
    d += ' C' + pt([A[N][0] + t1[0] * e1, A[N][1] + t1[1] * e1]) + ' ' + pt([B[N][0] + t1[0] * e1, B[N][1] + t1[1] * e1]) + ' ' + pt(B[N]);
    B.reverse();
    d += cr(B);
    d += ' C' + pt([B[N][0] - t0[0] * e0, B[N][1] - t0[1] * e0]) + ' ' + pt([A[0][0] - t0[0] * e0, A[0][1] - t0[1] * e0]) + ' ' + pt(A[0]);
    return d + ' Z';
  }
  // Короткая складка поперёк пальца на s: от смещения k0 до k1 (доли полуширины), выгиб bow к кончику
  function arcAt(f, s, k0, k1, bow) {
    const h = wid(f, s) / 2, p = off(f, s, h * k0), q = off(f, s, h * k1), m = off(f, s, h * (k0 + k1) / 2), k = tg(f, s);
    return 'M' + pt(p) + ' Q' + pt([m[0] + k[0] * bow * 2, m[1] + k[1] * bow * 2]) + ' ' + pt(q);
  }
  // Смещённая копия ломаной: на w вправо по ходу (при движении вправо — вниз)
  function shift(pts, w) {
    const n = pts.length;
    return pts.map((p, i) => {
      const a = pts[Math.max(0, i - 1)], b = pts[Math.min(n - 1, i + 1)], dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy) || 1;
      return [p[0] - dy / l * w, p[1] + dx / l * w];
    });
  }
  // Полоса вдоль ломаной pts шириной w (вправо по ходу)
  const band = (pts, w) => { const B = shift(pts, w); return shape(pts, [pts[pts.length - 1], B[B.length - 1]], B.slice().reverse(), [B[0], pts[0]]); };

  // =====================================================================================
  // Палец из фаланг: ось — гладкая кривая через [основание, сустав1, сустав2, кончик], ширины в этих точках.
  // На суставах палец чуть толще (костяшки), кончик скруглён. Все функции ниже работают в системе референса.
  // =====================================================================================
  function digit(pts, ws) {
    const S = [], M = 8, n = pts.length;
    for (let i = 0; i < n - 1; i++) {
      const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(n - 1, i + 2)];
      for (let j = 0; j < M || (i === n - 2 && j === M); j++) {
        const t = j / M, t2 = t * t, t3 = t2 * t;
        const x = 0.5 * (2 * p1[0] + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3);
        const y = 0.5 * (2 * p1[1] + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3);
        // гладкая кожа: без бугров на суставах, ширина плавно сходит к кончику
        S.push({ x: x, y: y, w: ws[i] + (ws[i + 1] - ws[i]) * t, s: (i + t) / (n - 1) });
      }
    }
    S.forEach((q, k) => {
      const a = S[Math.max(0, k - 1)], b = S[Math.min(S.length - 1, k + 1)], l = Math.hypot(b.x - a.x, b.y - a.y) || 1;
      q.tx = (b.x - a.x) / l; q.ty = (b.y - a.y) / l;
    });
    return { S: S, pts: pts, ws: ws };
  }
  // точка оси на доле s (0 — основание, 1 — кончик) со смещением k (доля полуширины, «+» — левая сторона по ходу)
  function dAt(D, s, k) {
    const S = D.S, f = Math.max(0, Math.min(S.length - 1.001, s * (S.length - 1))), i = Math.floor(f), t = f - i, a = S[i], b = S[i + 1];
    const x = a.x + (b.x - a.x) * t, y = a.y + (b.y - a.y) * t, w = a.w + (b.w - a.w) * t, tx = a.tx + (b.tx - a.tx) * t, ty = a.ty + (b.ty - a.ty) * t;
    const h = w / 2 * (k || 0);
    return { p: [x + ty * h, y - tx * h], t: [tx, ty], w: w };
  }
  // Полоса пальца между долями s0..s1 и смещениями k0..k1; cap — скругление дальнего конца (1 — полукруг)
  function dBand(D, s0, s1, k0, k1, cap, capBase) {
    const N = Math.max(4, Math.round((s1 - s0) * 24)), A = [], B = [];
    for (let i = 0; i <= N; i++) { const s = s0 + (s1 - s0) * i / N; A.push(dAt(D, s, k1).p); B.push(dAt(D, s, k0).p); }
    const e1 = dAt(D, s1, 0), e0 = dAt(D, s0, 0), r1 = 1.333 * (cap || 0) * e1.w * Math.abs(k1 - k0) / 4, r0 = 1.333 * (capBase || 0) * e0.w * Math.abs(k1 - k0) / 4;
    let d = 'M' + pt(A[0]) + cr(A);
    d += ' C' + pt([A[N][0] + e1.t[0] * r1, A[N][1] + e1.t[1] * r1]) + ' ' + pt([B[N][0] + e1.t[0] * r1, B[N][1] + e1.t[1] * r1]) + ' ' + pt(B[N]);
    B.reverse();
    d += cr(B);
    if (r0) d += ' C' + pt([B[N][0] - e0.t[0] * r0, B[N][1] - e0.t[1] * r0]) + ' ' + pt([A[0][0] - e0.t[0] * r0, A[0][1] - e0.t[1] * r0]) + ' ' + pt(A[0]);
    return d + ' Z';
  }
  const dFull = (D) => dBand(D, 0, 1, -1, 1, 1.05);
  // линия вдоль пальца со смещением k0 → k1
  function dLine(D, s0, s1, k0, k1) {
    const pts = [], N = Math.max(3, Math.round((s1 - s0) * 16));
    for (let i = 0; i <= N; i++) pts.push(dAt(D, s0 + (s1 - s0) * i / N, k0 + ((k1 == null ? k0 : k1) - k0) * i / N).p);
    return curve(pts);
  }
  // складка поперёк пальца на доле s от смещения k0 до k1, выгиб bow (к кончику > 0)
  function dCross(D, s, k0, k1, bow) {
    const a = dAt(D, s, k0), b = dAt(D, s, k1), m = dAt(D, s, (k0 + k1) / 2);
    return 'M' + pt(a.p) + ' Q' + pt([m.p[0] + m.t[0] * bow * 2, m.p[1] + m.t[1] * bow * 2]) + ' ' + pt(b.p);
  }
  // доля оси у сустава i (1 — первый сустав, 2 — второй)
  const dJ = (D, i) => D.js ? D.js[i] : i / (D.pts.length - 1);
  // Согнутый палец одной деталью: ось — ломаная по суставам, углы чуть скруглены (дважды срезаны по Чайкину),
  // поэтому излом на каждом суставе виден, но палец не распадается на отдельные «таблетки».
  // Точки пересчитаны по длине дуги; js — доли оси у суставов, ширина линейна между суставами.
  function bentDigit(pts, ws, cut) {
    let Q = pts.slice();
    for (let it = 0; it < 2; it++) {
      const R = [Q[0]];
      for (let i = 0; i < Q.length - 1; i++) {
        const a = Q[i], b = Q[i + 1];
        if (i > 0) R.push([a[0] + (b[0] - a[0]) * cut, a[1] + (b[1] - a[1]) * cut]);
        if (i < Q.length - 2) R.push([b[0] - (b[0] - a[0]) * cut, b[1] - (b[1] - a[1]) * cut]);
      }
      R.push(Q[Q.length - 1]);
      Q = R;
    }
    const len = [0];
    for (let i = 1; i < Q.length; i++) len.push(len[i - 1] + Math.hypot(Q[i][0] - Q[i - 1][0], Q[i][1] - Q[i - 1][1]));
    const seg = [0];
    for (let i = 1; i < pts.length; i++) seg.push(seg[i - 1] + Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]));
    const js = seg.map((v) => v / seg[seg.length - 1]), T = len[len.length - 1], S = [], M = 48;
    for (let k = 0, i = 0; k <= M; k++) {
      const s = k / M, l = s * T;
      while (i < Q.length - 2 && len[i + 1] < l) i++;
      const t = (l - len[i]) / ((len[i + 1] - len[i]) || 1);
      let j = 0;
      while (j < js.length - 2 && js[j + 1] < s) j++;
      const u = (s - js[j]) / ((js[j + 1] - js[j]) || 1);
      S.push({ x: Q[i][0] + (Q[i + 1][0] - Q[i][0]) * t, y: Q[i][1] + (Q[i + 1][1] - Q[i][1]) * t, w: ws[j] + (ws[j + 1] - ws[j]) * u, s: s });
    }
    S.forEach((q, k) => {
      const a = S[Math.max(0, k - 1)], b = S[Math.min(S.length - 1, k + 1)], l = Math.hypot(b.x - a.x, b.y - a.y) || 1;
      q.tx = (b.x - a.x) / l; q.ty = (b.y - a.y) / l;
    });
    return { S: S, pts: pts, ws: ws, js: js };
  }
  // Палец по фалангам: основание b, угол основной фаланги a0 (рад, экранные оси, y вниз), длина L (доли фаланг
  // 0.45 / 0.31 / 0.24), повороты на среднем (pip) и ногтевом (dip) суставах — полусогнутый палец с подогнутым
  // кончиком; ширины w0 у основания → w1 у кончика
  function finger(b, a0, L, pip, dip, w0, w1) {
    const pts = [b];
    let a = a0, p = b;
    [[0.45, pip], [0.31, dip], [0.24, 0]].forEach((s) => {
      p = [p[0] + Math.cos(a) * L * s[0], p[1] + Math.sin(a) * L * s[0]];
      a += s[1];
      pts.push(p);
    });
    return bentDigit(pts, [w0, w0 - (w0 - w1) * 0.35, w0 - (w0 - w1) * 0.7, w1], 0.22);
  }

  // =====================================================================================
  // Поза пары как на рендерах CS2 (реф 78 «Спортивные», 75 «Водительские» сняты одинаково): ближняя перчатка
  // тылом к нам, манжета слева вверху, сомкнутые полусогнутые пальцы уходят вниз-вправо, кончики подогнуты;
  // дальняя — позади справа вверху, повёрнута ладонью и ребром, большой палец сверху.
  // =====================================================================================
  function pose() {
    const near = {
      // указательный, средний, безымянный, мизинец: пальцы касаются друг друга (шаг осей чуть меньше ширины),
      // средний — самый длинный, указательный и безымянный короче, мизинец короче среднего на четверть
      // длины 0.9 / 1 / 0.95 / 0.75 от среднего; ногтевые фаланги подогнуты на ~34°, кончики уходят вниз
      f: [
        finger([192, 112], 0.56, 102, 0.3, 0.6, 32, 26),
        finger([171, 135], 0.5, 112, 0.3, 0.6, 33, 27),
        finger([150, 155], 0.48, 106, 0.3, 0.6, 31, 25),
        finger([128, 174], 0.5, 82, 0.3, 0.6, 27, 22),
      ],
      // большой палец: выходит из-под верхнего края кисти между перчатками, кончик над указательным
      th: finger([160, 54], 0.36, 100, 0.15, 0.3, 27, 21),
      // контур тыла: манжета (верх, низ), верхний край, нижний край (к костяшкам)
      cuffTop: [56, 12], cuffBot: [8, 94],
      top: [[56, 12], [100, 24], [144, 38], [178, 60], [202, 96]],
      bot: [[8, 94], [44, 134], [82, 164], [108, 180], [118, 186]],
    };
    // дальняя повёрнута на ~25° против ближней: пальцы веером уходят вправо, видны подушечки и ребро ладони
    const far = {
      f: [
        finger([290, 100], 0.36, 100, 0.18, 0.32, 25, 20),
        finger([281, 121], 0.53, 106, 0.2, 0.38, 26, 21),
        finger([267, 139], 0.74, 92, 0.22, 0.42, 24, 19),
        finger([251, 151], 0.9, 70, 0.22, 0.42, 21, 17),
      ],
      th: digit([[276, 34], [312, 54], [343, 82]], [28, 24, 18]),
      cuffTop: [230, 4], cuffBot: [168, 40],
    };
    return { near: near, far: far };
  }
  // Контур тыла ближней перчатки: верхний край → бугры костяшек над основаниями пальцев → нижний край
  function nearBack(N, reach) {
    const kn = knucklePts(N.f, reach);
    return shape(N.top, [N.top[N.top.length - 1]].concat(kn), [kn[kn.length - 1]].concat(N.bot.slice().reverse()), [N.bot[0], N.top[0]]);
  }
  // Точки костяшек: над каждым основанием пальца — выпуклый бугор на reach вдоль пальца, между ними — впадины
  function knucklePts(fs, reach) {
    const out = [];
    fs.forEach((D, i) => {
      const a = dAt(D, 0.02, 0), r = reach;
      out.push([a.p[0] + a.t[0] * r, a.p[1] + a.t[1] * r]);
      if (i < fs.length - 1) {
        const b = dAt(fs[i + 1], 0.02, 0);
        out.push([(a.p[0] + b.p[0]) / 2 + a.t[0] * (r - 5), (a.p[1] + b.p[1]) / 2 + a.t[1] * (r - 5)]);
      }
    });
    return out;
  }

  // Дальняя перчатка (общая для обеих моделей): ладонь и ребро, пальцы подушечками к нам, всё ролью q (темнее).
  // mat — основная кожа, palm — плоская накладка на пятке ладони (null — нет), deco(fr) — особые детали типа.
  // Пальцы — гладкие трубки: одна слабая складка на суставе, блик только на подушечке кончика.
  function farGlove(fr, mat, palm, deco) {
    // ладонь с манжетой: ребро ладони уходит под ближнюю перчатку
    F('q', shape([fr.cuffBot, fr.cuffTop, [262, 14], [290, 36], [302, 64], [300, 96]],
      [[300, 96], [292, 118], [278, 138], [260, 154], [236, 152], [200, 110], fr.cuffBot]), mat);
    // пальцы: мизинец → указательный (верхний ложится на нижний), затем большой поверх
    for (let i = 3; i >= 0; i--) F('q', dFull(fr.f[i]), mat);
    F('q', dFull(fr.th), mat);
    if (palm) {
      F('q', shape([[208, 44], [234, 34], [262, 40]], [[262, 40], [258, 62], [234, 76], [212, 66], [208, 44]]), palm);
      Ln('e', curve([[212, 48], [234, 40], [256, 44]]));
    }
    fr.f.forEach((D) => {
      Ln('d', dCross(D, dJ(D, 1), -0.7, 0.5, 1.2), 0.8);
      Ln('d', dCross(D, dJ(D, 2), -0.7, 0.5, 1.2), 0.8);
      Ln('h', dLine(D, 0.82, 0.95, 0.45, 0.2), 1.2);
    });
    Ln('d', dCross(fr.th, 0.5, -0.7, 0.5, 1.4), 0.8);
    Ln('h', dLine(fr.th, 0.8, 0.95, 0.45, 0.2), 1.2);
    // ребро ладони в тени и линия жизни
    Ln('d', curve([[292, 118], [278, 138], [260, 154]]), 2.4);
    Ln('d', curve([[240, 48], [252, 78], [262, 108], [258, 130]]), 0.9);
    if (deco) deco(fr);
  }

  // Пальцы ближней перчатки (тыл). Порядок: большой (в тени, роль q), затем от мизинца к указательному — верхний
  // палец ложится на нижний. Гладкая тонкая кожа: одна слабая складка на каждом суставе, блик — только на кончике.
  // Перед пальцами — тень ближней перчатки на дальней (полоса вдоль верхнего края), чтобы пара не сливалась.
  function nearDigits(N, mat) {
    Ln('d', curve(N.top.slice(1)), 9);
    Ln('d', dLine(N.th, 0.05, 0.92, 1.1, 1.1), 7);       // тень большого пальца на дальней
    Ln('d', dLine(N.f[0], 0.1, 0.9, 1.1, 1.1), 7);       // тень указательного на пальцах дальней
    F('p', dFull(N.th), mat);
    Ln('d', dCross(N.th, dJ(N.th, 1) + 0.02, -0.85, -0.2, 1), 0.7);
    Ln('h', dLine(N.th, 0.1, 0.5, 0.6, 0.55), 1.2);
    Ln('h', dLine(N.th, 0.82, 0.95, 0.5, 0.2), 1.4);
    for (let i = N.f.length - 1; i >= 0; i--) {
      const D = N.f[i];
      F('p', dFull(D), mat);
      Ln('d', dCross(D, dJ(D, 1) + 0.01, -0.85, -0.25, 1), 0.7);   // одна короткая складка на среднем суставе
      Ln('h', dLine(D, 0.8, 0.96, 0.5, 0.15), 1.5);
    }
  }

  // Линия поперёк оснований пальцев, сдвинутая вдоль пальцев на r (r < 0 — к запястью); концы — на краях кисти
  function kline(fs, r) {
    const n = fs.length - 1, sh = (a) => [a.p[0] + a.t[0] * r, a.p[1] + a.t[1] * r];
    return [sh(dAt(fs[0], 0.02, 0.95))].concat(fs.map((D) => sh(dAt(D, 0.02, 0))), [sh(dAt(fs[n], 0.02, -0.95))]);
  }
  // Полоса поперёк кисти между линиями r0 и r1 (накладка на костяшки)
  function kbar(fs, r0, r1) {
    const A = kline(fs, r0), B = kline(fs, r1).reverse();
    return shape(A, [A[A.length - 1], B[0]], B, [B[B.length - 1], A[0]]);
  }
  // Общее для обеих моделей: тень по линии костяшек (пальцы уходят вниз), тыл одной деталью (его вертикальный
  // переход света даёт форму: верх у манжеты светлее, низ к мизинцу темнее), блик верхнего края у запястья
  // и короткие блики на буграх костяшек — единственные яркие точки тыла
  function nearHand(N, mat) {
    Ln('d', curve(knucklePts(N.f, 12)), 3);
    F('p', nearBack(N, 8), mat);
    Ln('h', curve([[70, 22], [112, 34], [150, 50]]), 1.6);
    N.f.forEach((D, i) => {
      const a = dAt(D, 0.02, 0.55), t = a.t;
      Ln('h', 'M' + pt([a.p[0] - t[0] * 6, a.p[1] - t[1] * 6]) + ' Q' + pt([a.p[0] + t[0] * 3 - t[1] * 2, a.p[1] + t[1] * 3 + t[0] * 2]) +
        ' ' + pt([a.p[0] + t[0] * 2 - t[1] * (9 - i), a.p[1] + t[1] * 2 + t[0] * (9 - i)]), 1.4);
    });
  }

  // =====================================================================================
  // glsp — Спортивные перчатки (реф 78 «Ноктс» + фото велоперчаток): тонкая тёмная кожа, гладкие полусогнутые
  // пальцы, тонкая строченая панель-клин на тыле со светлым кантом (контрастная строчка), поле перфорации над
  // костяшками, низкий валик на костяшках, короткая манжета с тонким ремешком на липучке
  // =====================================================================================
  function sport() {
    P = [];
    const G = pose(), N = G.near, fr = G.far;
    // ----- дальняя: тёмная кожа, маленькая плоская накладка на пятке ладони, манжета с ремешком и рамкой -----
    farGlove(fr, 'od', 'darkleather!', () => {
      F('q', shape([[168, 40], [230, 4], [240, 10]], [[240, 10], [184, 50], [168, 40]]), 'darkleather!');
      F('q', rrect(196, 26, 24, 18, 4, -0.55), 'darkleather!');
      Ln('d', rrect(196, 26, 14, 9, 2, -0.55), 1.2);
      Ln('e', curve([[176, 36], [208, 18], [234, 6]]));
    });
    // ----- ближняя -----
    nearDigits(N, 'od');
    nearHand(N, 'od');
    // строченая панель-клин: верхний шов к костяшке среднего пальца, нижний — к безымянному
    const t1 = dAt(N.f[1], 0.02, 0.3), t2 = dAt(N.f[2], 0.02, -0.3);
    const up = [[92, 28], [128, 50], [154, 80], [t1.p[0] - t1.t[0] * 16, t1.p[1] - t1.t[1] * 16]];
    const lo = [[46, 126], [86, 142], [116, 150], [t2.p[0] - t2.t[0] * 16, t2.p[1] - t2.t[1] * 16]];
    Ln('d', curve(up), 1.2);
    Ln('e', curve(shift(up, -3.5)));
    Ln('d', curve(lo), 1.2);
    F('p', band(lo, 3.6), 'sage!');                   // светлый кант по нижнему шву
    Ln('e', curve(shift(lo, 6.5)));
    // поле перфорации между швами над костяшками: три ряда отверстий
    [-22, -29, -36].forEach((r, j) => {
      const L = kline(N.f, r).slice(1, 5), pts = [];
      for (let i = 0; i < L.length; i++) {
        pts.push(L[i]);
        if (i < L.length - 1) pts.push([(L[i][0] + L[i + 1][0]) / 2, (L[i][1] + L[i + 1][1]) / 2]);
      }
      Ln('d', dots(pts.slice(j === 2 ? 1 : 0, j === 2 ? 6 : 7)), 3);
    });
    // низкий валик на костяшках со строчкой
    F('p', kbar(N.f, -4, -13), 'od');
    Ln('e', curve(kline(N.f, -8.5)));
    Ln('h', curve(kline(N.f, -6).slice(0, 4)), 1.2);
    // короткая манжета (чуть темнее), светлый кант по шву и тонкий ремешок на липучке
    F('q', shape([N.cuffTop, [86, 20]], [[86, 20], [62, 70], [36, 125]], [[36, 125], [20, 108], N.cuffBot], [N.cuffBot, [30, 50], N.cuffTop]), 'od');
    F('p', band([[86, 20], [62, 70], [36, 125]], 3.2), 'sage!');
    Ln('e', curve([[78, 21], [55, 68], [29, 118]]));
    Ln('h', curve([[54, 16], [32, 52], [12, 90]]), 1.2);
    F('p', band([[70, 17], [48, 66], [24, 116]], 7), 'darkleather!');
    F('p', rrect(46, 68, 19, 14, 4, 1.12), 'darkleather!');
    Ln('d', rrect(46, 68, 11, 7, 2, 1.12), 1);
    return P;
  }

  // =====================================================================================
  // gldr — Водительские перчатки (реф 75 + фото): гладкая кожа, плетёная вставка на тыле от манжеты до середины
  // кисти, три крупных выреза над костяшками (видна тёмная подкладка), перфорация вдоль пальцев, узкая манжета
  // с одним язычком на кнопке; дальняя — светлая кожа с тёмной трикотажной полосой у оснований пальцев
  // =====================================================================================
  function driver() {
    P = [];
    const G = pose(), N = G.near, fr = G.far;
    // ----- дальняя -----
    farGlove(fr, 'bone', null, (q) => {
      q.f.slice(0, 3).forEach((D) => {
        const pts = [];
        for (let s = 0.16; s < 0.5; s += 0.085) pts.push(dAt(D, s, 0).p);
        Ln('d', dots(pts), 2.4);
      });
      F('k', kbar(q.f, 1, 13));
      Ln('e', curve(kline(q.f, 4)));
      Ln('e', curve(kline(q.f, 10)));
      Ln('e', curve([[176, 36], [208, 18], [234, 6]]));
    });
    // ----- ближняя: гладкие пальцы с рядом перфорации вдоль тыла -----
    nearDigits(N, 'leather');
    N.f.forEach((D) => {
      const pts = [];
      for (let s = 0.1; s < 0.64; s += 0.075) pts.push(dAt(D, s, -0.05).p);
      Ln('d', dots(pts), 2.8);
    });
    nearHand(N, 'leather');
    // три крупных выреза над костяшками: тёмная подкладка, строчка по краю; стенка у запястья в тени,
    // противоположная (к пальцам) освещена
    N.f.slice(0, 3).forEach((D) => {
      const a = dAt(D, 0.02, 0), t = a.t, c = [a.p[0] - t[0] * 11, a.p[1] - t[1] * 11], ang = Math.atan2(t[1], t[0]) + Math.PI / 2;
      const E = (rx, ry, th) => [c[0] + rx * Math.cos(th) * Math.cos(ang) - ry * Math.sin(th) * Math.sin(ang),
        c[1] + rx * Math.cos(th) * Math.sin(ang) + ry * Math.sin(th) * Math.cos(ang)];
      F('q', ell(c[0], c[1], 11.5, 9.5, ang), 'darkleather!');
      Ln('d', curve([0.6, 1.57, 2.5].map((th) => E(10, 8.2, th))), 2.4);
      Ln('h', curve([3.8, 4.71, 5.6].map((th) => E(10.3, 8.5, th))), 1.3);
      Ln('e', ell(c[0], c[1], 14.5, 12.5, ang));
    });
    // плетёная вставка — главный знак модели: мягкая ромбическая решётка в строченой рамке, до середины кисти
    const ca = 0.67, cA = Math.cos(ca), sA = Math.sin(ca), W = 34, H = 48, CX = 104, CY = 86;
    const LP = (x, y) => [CX + x * cA - y * sA, CY + x * sA + y * cA];
    F('p', rrect(CX, CY, 2 * W, 2 * H, 12, ca), 'tanleather');
    for (let c = -H - W + 11; c < H + W; c += 11) {
      [1, -1].forEach((sg) => {
        const y0 = Math.max(-H, Math.min(H, sg * -W + c)), y1 = Math.max(-H, Math.min(H, sg * W + c));
        const xa = (y0 - c) * sg, xb = (y1 - c) * sg;
        if (Math.abs(xb - xa) < 3) return;
        Ln('d', 'M' + pt(LP(xa, y0)) + ' L' + pt(LP(xb, y1)), 1.1);
        Ln('h', 'M' + pt(LP(xa, y0 - 1.8)) + ' L' + pt(LP(xb, y1 - 1.8)), 0.6);
      });
    }
    Ln('e', rrect(CX, CY, 2 * W + 7, 2 * H + 7, 14, ca));
    // узкая манжета: подогнутый край со строчкой
    F('p', shape([N.cuffTop, [76, 17]], [[76, 17], [52, 64], [26, 114]], [[26, 114], N.cuffBot], [N.cuffBot, [30, 50], N.cuffTop]), 'leather');
    Ln('e', curve([[68, 16], [45, 62], [20, 108]]));
    // язычок поперёк шва манжеты с крупной стальной кнопкой
    F('p', shape([[40, 36], [66, 42], [86, 48]], [[86, 48], [93, 58], [86, 68]], [[86, 68], [64, 64], [36, 56]], [[36, 56], [40, 36]]), 'leather');
    Ln('e', curve([[42, 41], [66, 46], [84, 52]]));
    F('l', ell(74, 54, 10.5, 10.5, 0));
    O(74, 54, 4.5);
    Ln('h', curve([[68, 48], [74, 46], [79, 48]]), 1.2);
    return P;
  }

  GEO.glsp = sport();
  GEO.gldr = driver();
})();
