'use strict';

// Перчатки на общей основе HAND (js/geo_hand.js): glsp (спортивные) — гладкая кожа с эластичными вставками,
// gldr (водительские) — тонкая облегающая кожа с вырезом на тыле и ремешком на кнопке.
// Кисть, поза и раскладка пары (HAND.PAIR: одна перчатка поверх другой, как на иконках CS2) — из HAND;
// здесь только характерные детали вида, крупно и без мелкой ряби.
// Загружается после js/geo_gloves*.js и js/geo_hand.js: GEO.<id> здесь заменяет прежнюю модель.
//
// Скин: окрашиваемые детали (без «!») — кожа; на каменном скине они становятся «крашеной кожей» в тон камня,
// а детали с подсказкой gem: 1 (накладка костяшек, нашивка, кант выреза, кнопка) — самим камнем.
// Детали с «!» (неопрен вставок, ремешок водительских) всегда своим материалом — пара не пёстрая.
(function () {
  if (typeof HAND === 'undefined') return;
  const f1 = (v) => Math.round(v * 10) / 10;
  const pt = (p) => f1(p[0]) + ',' + f1(p[1]);

  // ---------- Кривые в координатах модели (точки от h.at) ----------
  function cr(pts) {
    let d = '';
    for (let i = 0; i < pts.length - 1; i++) {
      const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
      d += ' C' + pt([p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6]) + ' ' +
        pt([p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6]) + ' ' + pt(p2);
    }
    return d;
  }
  // замкнутый контур из гладких участков; на стыках — изломы
  function shape(runs) {
    let d = 'M' + pt(runs[0][0]);
    runs.forEach((r) => { d += cr(r); });
    return d + ' Z';
  }
  // Эллипс в координатах кисти, повёрнутый на ang (рад, от оси u)
  function ellUV(h, cu, cv, ru, rv, ang) {
    const q = [], c = Math.cos(ang || 0), s = Math.sin(ang || 0);
    for (let i = 0; i < 10; i++) {
      const f = i * Math.PI / 5, x = Math.cos(f) * ru, y = Math.sin(f) * rv;
      q.push([cu + x * c - y * s, cv + x * s + y * c]);
    }
    return h.loop(q);
  }

  const FINGERS = ['pinky', 'ring', 'middle', 'index'];
  const H = HAND.HINT;

  // ---------- Общее для обеих моделей ----------
  // Пальцы и тыльная сторона одним материалом; складки только в суставах (едва заметные).
  // В щелях между сомкнутыми пальцами — тень (h.webs), не фон.
  function handBody(P, h, mat, crease) {
    P.push(['q', h.webs(), mat, H.web]);
    P.push(['p', h.thumb(), mat, H.finger]);
    FINGERS.forEach((n) => P.push(['p', h.finger(n), mat, H.finger]));
    if (crease) {
      FINGERS.forEach((n) => P.push(['d', h.joint(n, 1, 0.7), 0.5]));
    }
  }
  // Большой палец поверх края ладони (после тыльной стороны) и складка, где он выходит из-под неё
  function thumbTop(P, h, mat) {
    P.push(['p', h.thumbOver(), mat, H.finger]);
    P.push(['d', h.thumbFold(), 0.9]);
    P.push(['d', h.joint('thumb', 2, 0.7), 0.5]);
  }

  // =====================================================================================
  // glsp — Спортивные перчатки: гладкая кожа, по тылу от манжеты к безымянному пальцу — широкий двухцветный
  // клин-вставка (неопрен с полосой в цвет кожи), на тыле со стороны большого пальца — крупная овальная нашивка,
  // широкая липучка на манжете с язычком. Камень (gem): нашивка на тыле.
  // =====================================================================================
  function sport() {
    const h = HAND.make({ cuffLen: 30, cuffW: 62, flare: 2, puff: 0.98 }), P = [];
    const cH = 31, cL = 30;
    const rg = h.at('ring', 0.02, 0), rgA = h.at('ring', 0.06, -1.05), rgB = h.at('ring', 0.06, 0.95);
    handBody(P, h, 'leather', true);
    P.push(['p', h.back(), 'leather', H.leather]);
    thumbTop(P, h, 'leather');
    // клин-вставка: широкий у запястья (вся сторона мизинца), сходится к основанию безымянного
    P.push(['p', shape([[h.pt(4, -29), h.pt(30, -30.5), h.pt(56, -26), rgA], [rgA, rg, rgB],
      [rgB, h.pt(54, 0), h.pt(30, 10), h.pt(4, 14)], [h.pt(4, 14), h.pt(2, -8), h.pt(4, -29)]]), 'neoprene!', { pr: 'pillow', r: 4, h: 1 }]);
    // полоса в цвет кожи по середине клина — двухцветная вставка
    P.push(['p', shape([[h.pt(4, -14), h.pt(32, -14), h.pt(58, -12.5), h.at('ring', 0.03, -0.3)],
      [h.at('ring', 0.03, -0.3), h.at('ring', 0.03, 0.15)],
      [h.at('ring', 0.03, 0.15), h.pt(58, -6), h.pt(32, -3), h.pt(4, -1)], [h.pt(4, -1), h.pt(3, -8), h.pt(4, -14)]]),
      'leather', { pr: 'pillow', r: 2.5, h: 1.6 }]);
    P.push(['e', h.curve([[6, -27], [30, -28], [56, -23.5], [72, -15]])]);
    P.push(['e', h.curve([[6, 11.5], [30, 7.5], [54, -2], [72, -2]])]);
    // крупная овальная нашивка на тыле — камень
    P.push(['p', ellUV(h, 46, 21, 14, 9.5, -0.1), 'darkleather', { pr: 'round', r: 3, h: 2, gem: 1 }]);
    P.push(['e', ellUV(h, 46, 21, 11, 6.8, -0.1)]);
    // манжета: резинка запястья (неопрен с рубчиком), поверх — широкая липучка
    P.push(['k', h.cuffHole()]);
    P.push(['p', h.cuff(), 'neoprene!', H.cloth]);
    P.push(['d', h.cuffLine(3), 0.6]);
    P.push(['p', h.cuff(-4, -cL), 'darkleather', { pr: 'pillow', r: 4, h: 1.5 }]);
    // язычок липучки (свободный конец ремня) с круглым концом к большому пальцу
    P.push(['p', h.shape([[[-7, -cH + 1.5], [-7, 4]], [[-7, 4], [-9.5, 11], [-17.5, 14], [-25.5, 11], [-28, 4]],
      [[-28, 4], [-28, -cH + 1.5]], [[-28, -cH + 1.5], [-17.5, -cH + 1], [-7, -cH + 1.5]]]), 'darkleather', { pr: 'pillow', r: 3, h: 2.5 }]);
    P.push(['e', h.curve([[-9.5, -cH + 3], [-9.5, 4], [-12, 9.5], [-17.5, 11.5], [-23, 9.5], [-25.5, 4], [-25.5, -cH + 3]])]);
    return P;
  }

  // =====================================================================================
  // gldr — Водительские перчатки: тонкая облегающая кожа (пальцы тоньше), на тыле аккуратная арка-вырез
  // от манжеты (видна тёмная подкладка) и четыре овальных отверстия над костяшками, короткая манжета;
  // поперёк выреза — тёмный ремешок с кнопкой. Камень (gem): кант выреза и кнопка ремешка.
  // =====================================================================================
  function driver() {
    const h = HAND.make({ cuffLen: 24, cuffW: 58, flare: 1, puff: 0.92 }), P = [];
    const cL = 24;
    const at = (n, d, s) => h.at(n, d / h.len(n), s);
    handBody(P, h, 'tanleather', true);
    P.push(['p', h.back(), 'tanleather', H.leather]);
    thumbTop(P, h, 'tanleather');
    // отверстия над костяшками: овалы вдоль пальцев, тёмная подкладка чуть утоплена
    FINGERS.forEach((n) => {
      const c = at(n, -12, 0), e = at(n, -8, 0), a = Math.atan2(e[1] - c[1], e[0] - c[0]);
      const ra = n === 'pinky' ? 4.6 : 5.4, rb = n === 'pinky' ? 2.9 : 3.3, q = [];
      for (let i = 0; i < 10; i++) {
        const f = i * Math.PI / 5, x = Math.cos(f) * ra, y = Math.sin(f) * rb;
        q.push([c[0] + x * Math.cos(a) - y * Math.sin(a), c[1] + x * Math.sin(a) + y * Math.cos(a)]);
      }
      P.push(['k', shape([q.concat([q[0]])]), { pr: 'round', r: 1.5, h: -1.5 }]);
    });
    // короткая манжета с подгибом
    P.push(['k', h.cuffHole()]);
    P.push(['p', h.cuff(), 'tanleather', H.cuff]);
    P.push(['e', h.cuffLine(-cL + 4)]);
    // арка-вырез на тыле: от открытого края манжеты до середины кисти, по краю — кант со строчкой
    const u1 = -cL - 2;
    P.push(['k', h.shape([[[u1, -15], [-2, -16], [18, -13.5], [30, -6], [33.5, 1.5]],
      [[33.5, 1.5], [30, 9], [18, 16.5], [-2, 19.5], [u1, 18.5]],
      [[u1, 18.5], [u1 - 1.5, 1.5], [u1, -15]]]), { pr: 'pillow', r: 4, h: -2 }]);
    // кант выреза — твёрдая окантовка (на каменном скине — камень)
    const rimIn = [[u1, -15], [-2, -16], [18, -13.5], [30, -6], [33.5, 1.5], [30, 9], [18, 16.5], [-2, 19.5], [u1, 18.5]];
    const rimOut = [[u1, -19.5], [-2, -20.5], [19.5, -17.8], [33.8, -9.2], [38, 1.5], [33.8, 12.2], [19.5, 20.8], [-2, 24], [u1, 23]];
    P.push(['p', h.shape([rimOut, [rimOut[8], [u1 - 1, 20.8], rimIn[8]], rimIn.slice().reverse(), [rimIn[0], [u1 - 1, -17.3], rimOut[0]]]),
      'darkleather', { pr: 'round', r: 2, h: 1, gem: 1 }]);
    // ремешок поперёк выреза и кнопка на нём
    P.push(['p', h.cuff(-5, -16), 'darkleather!', { pr: 'pillow', r: 3.5, h: 2.5 }]);
    P.push(['p', ellUV(h, -10.5, 1.5, 6.6, 6.6), 'steel', { pr: 'dome', r: 5, h: 1, gem: 1 }]);
    return P;
  }

  GEO.glsp = HAND.geo(sport());
  GEO.gldr = HAND.geo(driver());
})();
