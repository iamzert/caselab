    P.push(['h', curve(FT.pts([[FL * 0.24, ft.hb * 0.84], [FL * 0.5, ft.hb * 0.82], [FL * 0.74, ft.ht * 0.8]])), 0.9]);
    // манжета задней перчатки: подгиб со строчкой, край ремешка, окантовка по шву с ладонью
