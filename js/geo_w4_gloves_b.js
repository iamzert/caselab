    TC.far.forEach((f, i) => {
      const F = frame(f.B, f.T, f.bend), L = F.L;
      P.push(['q', digit(F, f.hb, f.ht), body]);
      // колпачок кончика по скруглению; узкая замшевая вставка над средним суставом — у каждого пальца своя
      P.push(['q', tipCap(F, L * 0.79, f.ht), body]);
      {
        const c = L * [0.5, 0.53, 0.49][i], h = [3.2, 4.4, 3.8][i];
        P.push(['q', F.rr(c - h, c + h, -f.hb * 0.8, f.hb * [0.6, 0.78, 0.7][i], 2.4), suede]);
      }
      P.push(['d', across(F, L * 0.27, f.hb, 0.7, -1.2) + across(F, L * 0.71, f.ht, 0.72, -1), 0.9]);
      P.push(['e', across(F, L * 0.79 + 2.2, f.ht, 0.76, -2)]);
      if (i > 0) P.push(['h', curve(F.pts([[L * 0.15, f.hb * 0.84], [L * 0.42, f.hb * 0.86], [L * 0.72, f.ht * 0.84]])), 0.9]);
    });
    // ладонь (закрывает основания пальцев), усиление между большим и указательным, складки
    P.push(['q', blob([[178, 76], [190, 62], [210, 52], [236, 44], [266, 40], [292, 46], [300, 74], [290, 106], [262, 128],
      [234, 140], [214, 138], [207, 128], [201, 116], [196, 103], [191, 90]]), body]);
    P.push(['q', blob([[182, 84], [188, 71], [202, 62], [222, 57], [231, 63], [219, 69], [203, 77], [192, 89]]), suede]);
    P.push(['e', curve([[186, 82], [192, 72], [205, 65], [222, 61]])]);
    P.push(['d', curve([[196, 101], [212, 96], [230, 86]]) + curve([[203, 114], [222, 108], [242, 97]]), 0.9]);
    // большой палец задней перчатки — сверху, лежит на ладони
    const ft = TC.fthumb, FT = frame(ft.B, ft.T, ft.bend), FL = FT.L;
    P.push(['q', digit(FT, ft.hb, ft.ht), body]);
    P.push(['q', tipCap(FT, FL * 0.78, ft.ht), body]);
    P.push(['q', FT.rr(FL * 0.5 - 3.6, FL * 0.5 + 3.6, -ft.hb * 0.84, ft.hb * 0.46, 2.4), suede]);
