'use strict';

// Перчатки по рендерам CS2 (референс tools/refs/79.png) и фото (tools/refs/web/gloves): gltc (тактические), glmo (мотоперчатки).
// Загружается после js/geo_gloves*.js: GEO.<id> здесь заменяет прежнюю модель.
// Модель строится в координатах референса (как картинка в игре: манжета слева, пальцы вправо-вниз), затем переводится
// в поле 512×192 с отражением по x — рендерер отражает картинку обратно, и пара лежит как в CS2.
// Каждая перчатка — в своей системе «кисти»: u — от запястья к пальцам, v — поперёк (v > 0 — сторона большого пальца).
// Передняя перчатка — тыльной стороной к нам; задняя (выше и правее, под углом) — ладонью, её окраска — роль q (темнее).
(function () {
  // ---------- перевод координат ----------
  const K = 0.72, X0 = 140, RX0 = 10, RY0 = 34;                 // референс → поле (масштаб и сдвиг)
  const r1 = (v) => Math.round(v * 10) / 10;
  let G = { o: [0, 0], a: 0, s: 1, f: 1 };                     // текущая перчатка: запястье, угол оси, масштаб, зеркало
  // flip — другая рука (левая): сторона большого пальца уходит вниз, мизинец — наверх
  const place = (o, aDeg, s, flip) => { G = { o: o, a: aDeg * Math.PI / 180, s: s, f: flip ? -1 : 1 }; };
  // кисть (u, v) → референс → поле
  function toField(u, v) {
    const c = Math.cos(G.a), s = Math.sin(G.a);
    v *= G.f;
    const rx = G.o[0] + G.s * (u * c + v * s), ry = G.o[1] + G.s * (u * s - v * c);
    return [512 - (X0 + (rx - RX0) * K), 4 + (ry - RY0) * K];
  }
  const pt = (q) => { const f = toField(q[0], q[1]); return r1(f[0]) + ',' + r1(f[1]); };
  const lerp = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];

  // Замкнутый сглаженный контур (Catmull-Rom → Безье); точка [u, v, 1] — острый угол
  function blob(pts, t) {
    t = t == null ? 1 : t;
    const n = pts.length;
    let d = 'M' + pt(pts[0]);
    for (let i = 0; i < n; i++) {
      const p0 = pts[(i - 1 + n) % n], p1 = pts[i], p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
      const k1 = p1[2] ? 0 : t / 6, k2 = p2[2] ? 0 : t / 6;
      d += ' C' + pt([p1[0] + (p2[0] - p0[0]) * k1, p1[1] + (p2[1] - p0[1]) * k1]) +
        ' ' + pt([p2[0] - (p3[0] - p1[0]) * k2, p2[1] - (p3[1] - p1[1]) * k2]) + ' ' + pt(p2);
    }
    return d + ' Z ';
  }
  // Незамкнутая сглаженная линия
  function curve(pts, t) {
    t = t == null ? 1 : t;
    const n = pts.length;
    let d = 'M' + pt(pts[0]);
    for (let i = 0; i < n - 1; i++) {
      const p0 = pts[Math.max(i - 1, 0)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(i + 2, n - 1)];
      d += ' C' + pt([p1[0] + (p2[0] - p0[0]) * t / 6, p1[1] + (p2[1] - p0[1]) * t / 6]) +
        ' ' + pt([p2[0] - (p3[0] - p1[0]) * t / 6, p2[1] - (p3[1] - p1[1]) * t / 6]) + ' ' + pt(p2);
    }
    return d + ' ';
  }
  const poly = (pts, close) => pts.map((p, i) => (i ? 'L' : 'M') + pt(p)).join(' ') + (close ? ' Z ' : ' ');
  // заклёпка / кнопка в точке кисти
  const rivet = (u, v, r) => { const f = toField(u, v); return ['o', r1(f[0]), r1(f[1]), r1(r * K * G.s)]; };
  // эллипс в системе кисти (выпуклые накладки, кнопки)
  const oval = (cu, cv, ru, rv) => blob([[cu - ru, cv], [cu, cv + rv], [cu + ru, cv], [cu, cv - rv]]);

  // Палец из трёх фаланг: ось от основания B (кисть) под углом ang° к u (+ к большому пальцу), длины фаланг ln[0..2],
  // сгибы в суставах j[0] (средний, PIP) и j[1] (ногтевой, DIP), ° (< 0 — к v−: кончик подогнут вниз, под палец).
  // at(s, w): s — вдоль оси, w — поперёк (w > 0 — сторона большого пальца); у суставов нормаль сглажена (R)
  function finger(B, ang, ln, j) {
    const segs = [];
    let p = B, a = ang * Math.PI / 180, s0 = 0;
    for (let i = 0; i < 3; i++) {
      if (i) a += j[i - 1] * Math.PI / 180;
      segs.push({ p: p, a: a, l: ln[i], s0: s0 });
      p = [p[0] + ln[i] * Math.cos(a), p[1] + ln[i] * Math.sin(a)];
      s0 += ln[i];
    }
    const L = s0, R = 4;
    const at = (s, w) => {
      const i = s < segs[1].s0 ? 0 : s < segs[2].s0 ? 1 : 2, g = segs[i], e = s - g.s0;
      let n = g.a;
      if (i > 0 && e < R) n = segs[i - 1].a + (g.a - segs[i - 1].a) * (0.5 + e / (2 * R));
      else if (i < 2 && g.l - e < R) n = g.a + (segs[i + 1].a - g.a) * (0.5 - (g.l - e) / (2 * R));
      return [g.p[0] + e * Math.cos(g.a) - Math.sin(n) * w, g.p[1] + e * Math.sin(g.a) + Math.cos(n) * w];
    };
    return { L: L, s1: ln[0], s2: ln[0] + ln[1], at: at, pts: (list) => list.map((q) => at(q[0], q[1]).concat(q[2] ? [1] : [])) };
  }
  // Контур пальца: у основания полуширина hb, у кончика ht; крупные утолщения на суставах (s1, s2) — костяшки видны,
  // палец читается согнутым. Основание (s = -6) уходит под ладонь
  function digitPath(F, hb, ht) {
    const L = F.L, a = F.s1, b = F.s2, m = (hb + ht) / 2;
    const side = [[a * 0.45, hb], [a, m + 1], [(a + b) / 2, m * 0.95], [b, ht + 0.5], [b + (L - b) * 0.4, ht * 0.96],
      [L - ht * 0.45, ht * 0.72]];
    const dn = side.map((q) => [q[0], -q[1]]).reverse();
    return blob(F.pts([[-6, hb, 1]].concat(side, [[L, 0]], dn, [[-6, -hb, 1]])));
  }
  // Накладка на фалангу: от s0 до s1, полуширины w0 → w1, скруглённые углы
  function padPath(F, s0, s1, w0, w1) {
    return blob(F.pts([[s0, 0], [s0 + 1, w0 * 0.9], [(s0 + s1) / 2, (w0 + w1) / 2], [s1 - 1, w1 * 0.9], [s1, 0],
      [s1 - 1, -w1 * 0.9], [(s0 + s1) / 2, -(w0 + w1) / 2], [s0 + 1, -w0 * 0.9]]), 0.7);
  }
  // Поперечная складка сустава на пальце (дуга к кончику)
  const crease = (F, s, w, bow) => curve(F.pts([[s, w], [s + (bow == null ? 2 : bow), 0], [s, -w]]));
  // Блик вдоль освещённого края пальца (свет сверху-слева в игре — сторона v > 0 у обеих перчаток)
  const ridge = (F, w0, w1, a, b) => curve(F.pts([[F.L * (a || 0.12), w0], [F.L * 0.45, (w0 + w1) / 2], [F.L * (b || 0.78), w1]]));

  // ---------- анатомия кисти (общая для обеих моделей) ----------
  // Пальцы длинные и тонкие, разной длины (средний длиннее всех, мизинец ~0.75 и посажен ближе к запястью), лёгкий веер —
  // согнутые пальцы прижаты друг к другу и чуть перекрываются (шаг 21 при толщине 21–24). Видимая длина укорочена
  // ракурсом; фаланги 0.46 / 0.30 / 0.24; ногтевая фаланга подогнута сильнее средней
  const FING = [
    { B: [72, -30], ang: -6, L: 58, hb: 9.2, ht: 8.2, j: [-14, -30] },     // мизинец (~0.75 среднего)
    { B: [88, -10], ang: -2.5, L: 71, hb: 9.8, ht: 8.8, j: [-14, -32] },   // безымянный
    { B: [93, 10.5], ang: 0, L: 78, hb: 10.2, ht: 9.1, j: [-14, -32] },     // средний — самый длинный
    { B: [88, 31], ang: 2, L: 70, hb: 9.8, ht: 8.8, j: [-12, -30] },       // указательный
  ];
  const lnOf = (L) => [L * 0.46, L * 0.3, L * 0.24];
  // Большой палец отведён от оси пальцев (~55°, от оси кисти 46°) к стороне манжеты и огибает ребро кисти; короткий, с перепонкой
  const THUMB = { B: [30, 41], ang: 46, L: 44, hb: 13, ht: 10.6, j: [-12, -22] };
  // Кисть тыльной стороной: запястье сужено (~30 % уже основания пальцев) → дуга костяшек (к мизинцу уходит к запястью)
  const PALM = [[-8, -29, 1], [8, -31], [28, -41], [54, -46], [74, -46], [88, -38], [97, -21], [101, 0], [100, 22],
    [95, 40], [80, 48], [58, 47], [30, 43], [10, 32], [-8, 30, 1]];
  // Собственная тень пальца на соседнем (свет сверху-слева: тень вниз, к стороне мизинца)
  const gapShade = (F, f) => ['d', curve(F.pts([[F.L * 0.02, -(f.hb + 0.5)], [F.s1, -(f.hb + f.ht) / 2 - 1.6],
    [F.L * 0.86, -(f.ht + 0.3)]])), 2.4];
  // Одна складка на сустав: средний (PIP) и ногтевой (DIP)
  const knuck = (F, f) => [['d', crease(F, F.s1, (f.hb + f.ht) * 0.42, 2.2), 1.1],
    ['d', crease(F, F.s2, f.ht * 0.72, 1.4), 0.8]];
  // Рамки пальцев: k — укорочение (согнуты к зрителю), dA — общий сгиб в пястных суставах (< 0 — к мизинцу),
  // jk — усиление сгиба суставов; c — сжатие кисти поперёк (ракурс)
  const frames = (k, dA, jk, c) => FING.map((f) => finger([f.B[0], f.B[1] * (c || 1)], f.ang + (dA || 0), lnOf(f.L * k),
    [f.j[0] * (jk || 1), f.j[1] * (jk || 1)]));
  const thumbFrame = (k, dAng, c) => finger([THUMB.B[0], THUMB.B[1] * (c || 1)], THUMB.ang + (dAng || 0), [THUMB.L * k * 0.42,
    THUMB.L * k * 0.33, THUMB.L * k * 0.25], THUMB.j);
  // Перепонка между большим пальцем и ребром кисти (рисуется до пальца и ладони)
  const webPath = (T, c) => blob([[34, 41 * c], [T.at(T.L * 0.45, -THUMB.hb * 0.7)[0], T.at(T.L * 0.45, -THUMB.hb * 0.7)[1]],
    [62, 46 * c], [50, 40 * c]], 0.9);
  // Расширяющаяся манжета: от u0 (у запястья, полуширина w0) до конца u1 (полуширина w1)
  const cuffPath = (u0, u1, w0, w1) => blob([[u0, -w0, 1], [u0 + 4, 0], [u0, w0, 1], [(u0 + u1) / 2, (w0 + w1) / 2 + 1],
    [u1, w1, 1], [u1 - 3, 0], [u1, -w1, 1], [(u0 + u1) / 2, -(w0 + w1) / 2 - 1]], 0.9);
  // Поперечная полоса по манжете (ремешок, подгиб): от u0 до u1, полуширина w (с запасом под контур)
  const bandPath = (u0, u1, w0, w1) => blob([[u0, -w0, 1], [u0 + 2.5, 0], [u0, w0, 1], [u1, w1, 1], [u1 + 2.5, 0], [u1, -w1, 1]], 0.9);

  // Строчка вдоль контура со сдвигом внутрь (точки контура и центр, к которому сдвигаем)
  const inset = (pts, c, d) => pts.map((q) => {
    const dx = c[0] - q[0], dy = c[1] - q[1], l = Math.hypot(dx, dy) || 1;
    return [q[0] + dx / l * d, q[1] + dy / l * d];
  });
  // Стёжка «ромбом» по области u0..u1, v0..v1 (шаг st поперёк, наклон линий m = tg угла к оси кисти),
  // обрезанная овалом области. При m ≈ 0.58 (30°) на картинке получаются ромбы, а не квадратная сетка
  function quilt(u0, u1, v0, v1, st, m) {
    let d = '';
    m = m || 0.58;
    const cu = (u0 + u1) / 2, cv = (v0 + v1) / 2, ru = (u1 - u0) / 2, rv = (v1 - v0) / 2;
    const inside = (u, v) => ((u - cu) / ru) ** 2 + ((v - cv) / rv) ** 2 <= 1;
    for (let k = -8; k <= 8; k++) {
      [1, -1].forEach((sg) => {
        const seg = [];
        for (let t = -60; t <= 60; t += 2) {
          const u = cu + t, v = cv + sg * m * t + (k + 0.5) * st;
          if (inside(u, v)) seg.push([u, v]);
        }
        if (seg.length > 3) d += poly([seg[0], seg[seg.length - 1]]);
      });
    }
    return d;
  }

  // ---------- Тактические перчатки (gltc) ----------
  // Ткань 'coyote' (скин), матовая: тонкие блики, без бликов-звёзд, строчка по швам пальцев. Жёсткая защита — свой
  // материал (роль 'k', тёмный полимер): почти прямая полоса на костяшках (пястные суставы) с 4 буграми над основаниями
  // пальцев, по одной накладке на основных фалангах, накладка на большом пальце. Запястье сужено, манжета расходится
  // раструбом; ремень-липучка и D-кольцо. Передняя (правая) — тыльной стороной к нам; задняя (левая) — ладонью к нам,
  // наполовину закрыта передней. Свет сверху-слева — сторона v > 0 и запястье.
  // дуга пястных суставов тактической: почти прямая, с небольшим наклоном к мизинцу
  const tArc = (v) => 91 + 0.1 * v - 0.003 * v * v;
  function knuckleGuard(P) {
    const vs = [-38, -28, -18, -8, 2, 12, 22, 32, 41];
    const n = vs.length;
    const top = vs.map((v) => [tArc(v) - 11, v]), bot = vs.map((v) => [tArc(v) + 4, v]).reverse();
    P.push(['d', curve(vs.slice(1, -1).map((v) => [tArc(v) + 8, v])), 3.5]);          // мягкая тень полосы на пальцах
    P.push(['k', blob(top.concat(bot).map((q, i) => (i === 0 || i === n - 1 || i === n || i === 2 * n - 1 ? q.concat([1]) : q)), 0.8)]);
    FING.forEach((f) => {
      const v = f.B[1] * 0.96, u = tArc(v) - 3.5;
      P.push(['k', oval(u, v, 5, 7.2)]);
      P.push(['h', curve([[u - 2.6, v + 5], [u - 4, v + 1], [u - 3, v - 3.5]]), 1.2]);
    });
    P.push(['h', curve(vs.slice(1, -1).map((v) => [tArc(v) - 9.6, v])), 1.4]);       // фаска по верхнему краю
  }
  function tactical() {
    const P = [], body = 'coyote';
    // палец: одна жёсткая накладка на основной фаланге, по складке на сустав, шов сбоку (объём — от общего света)
    const digit = (role, F, f, pad) => {
      P.push([role, digitPath(F, f.hb, f.ht), body]);
      if (pad) P.push(['k', padPath(F, F.L * 0.15, F.s1 - 2.5, f.hb * 0.5, f.hb * 0.44)]);
      knuck(F, f).forEach((q) => P.push(q));
      P.push(['e', curve(F.pts([[F.s1 + 1, -f.hb * 0.62], [(F.s1 + F.s2) / 2, -f.ht * 0.66], [F.L * 0.9, -f.ht * 0.5]]))]);
    };

    // --- задняя перчатка (левая): ладонью к нам, за передней; пальцы согнуты к зрителю (короче, подогнуты ниже) ---
    const c = 0.86;
    place([166, 100], 20, 1.36);
    P.push(['q', cuffPath(6, -30, 29 * c, 40 * c), body]);
    P.push(['q', bandPath(-24, -31, 38 * c, 40.5 * c), body]);
    frames(0.7, -14, 1.5, c).forEach((F, i) => {
      if (i) P.push(gapShade(F, FING[i]));
      digit('q', F, FING[i], false);
    });
    P.push(['q', blob(PALM.map((q) => [q[0], q[1] * c].concat(q[2] ? [1] : []))), body]);
    // усиленная ладонь — светлый замш (не чёрный: не сливается с полосой передней перчатки), строчка по краю
    const pp = [[12, -20], [44, -27], [70, -26], [80, -10], [78, 10], [60, 20], [30, 18], [12, 6]].map((q) => [q[0], q[1] * c]);
    P.push(['p', blob(pp, 0.9), 'sand']);
    P.push(['e', blob(inset(pp, [46, -2], 2.6), 0.9)]);
    P.push(['d', curve([[30, 22 * c], [52, 2], [80, -14 * c]]), 1.2]);
    // контровой свет по верхнему краю задней перчатки — пара читается как две кисти
    P.push(['h', curve([[-26, -38 * c], [6, -29 * c], [28, -41 * c], [60, -47 * c], [86, -40 * c], [98, -22 * c]]), 1.8]);
    const RT = thumbFrame(0.9, -20, c);
    P.push(['q', digitPath(RT, THUMB.hb, THUMB.ht), body]);
    P.push(['d', crease(RT, RT.s1, THUMB.ht * 0.9, 2), 1.1]);
    P.push(['h', ridge(RT, THUMB.hb * 0.8, THUMB.ht * 0.76, 0.2, 0.85), 1]);

    // --- передняя перчатка (правая): тыльной стороной; пальцы согнуты в пястных суставах ---
    place([76, 126], 26, 1.56);
    P.push(['d', curve([[56, 60], [80, 62], [98, 57]]), 7]);               // тень передней перчатки на задней
    const T = thumbFrame(1, -16);
    P.push(['p', webPath(T, 1), body]);
    P.push(['p', digitPath(T, THUMB.hb, THUMB.ht), body]);
    P.push(['k', padPath(T, T.s1 - 6, T.s1 + 4, THUMB.hb * 0.56, THUMB.ht * 0.56)]);
    P.push(['d', crease(T, T.s2, THUMB.ht * 0.72, 1.4), 0.8]);
    P.push(['h', ridge(T, THUMB.hb * 0.8, THUMB.ht * 0.76, 0.2, 0.85), 0.9]);
    frames(1, -10).forEach((F, i) => {
      if (i) P.push(gapShade(F, FING[i]));
      digit('p', F, FING[i], true);
    });
    // тыльная сторона кисти: вставка по ребру ладони (плавно сходит к запястью), стёганая панель
    P.push(['p', blob(PALM), body]);
    P.push(['d', curve(T.pts([[T.L * 0.08, -THUMB.hb - 1], [T.L * 0.3, -THUMB.hb * 0.9]])), 1.4]);   // складка перепонки
    P.push(['q', blob([[-8, -29, 1], [8, -31], [28, -41], [54, -46], [70, -45], [66, -39], [50, -38], [28, -33], [8, -26], [-8, -24, 1]]), 'sand']);
    P.push(['e', curve([[-6, -26], [10, -28.5], [28, -35], [52, -40], [64, -41]])]);
    const pan = [[28, -30], [52, -35], [66, -30], [76, -12], [78, 6], [72, 26], [54, 35], [32, 30], [20, 0]];
    P.push(['p', blob(pan), body]);
    P.push(['d', quilt(20, 80, -34, 36, 19), 0.9]);
    P.push(['e', blob(inset(pan, [50, 0], 2.6))]);
    // объём: узкий блик по освещённому краю, затемнение дальнего края (ткань матовая)
    P.push(['h', curve([[6, 24], [28, 33], [52, 37], [70, 35]]), 1.8]);
    P.push(['d', curve([[10, -20], [32, -26], [56, -31], [74, -28]]), 3]);
    knuckleGuard(P);
    // манжета: от суженного запястья раструбом; подгиб на конце
    P.push(['p', cuffPath(6, -30, 30, 41), body]);
    P.push(['q', bandPath(-25, -31, 40, 41.5), body]);
    // ремень-липучка поперёк манжеты: рифлёная нашивка, строчка по краям, D-кольцо на стороне мизинца
    P.push(['m', blob([[-6, -35], [-3, -42], [-10, -46.5], [-20, -44.5], [-23, -38], [-19, -40], [-10, -41.5], [-9, -35]], 0.6)]);
    P.push(['p', bandPath(-4, -21, 33.5, 38.5), body]);
    P.push(['e', curve([[-6, -31], [-5, 0], [-6, 32]]) + curve([[-19, -35], [-18, 0], [-19, 36]])]);
    P.push(['k', blob([[-8, -26, 1], [-7, 26, 1], [-17, 29, 1], [-18, -29, 1]], 0.5)]);
    P.push(['d', [-22, -12, -2, 8, 18].map((v) => curve([[-9, v], [-16, v + 6]])).join(''), 0.8]);
    P.push(['h', curve([[-3, -31], [-1.5, 0], [-3, 32]]), 1.2]);
    P.push(['d', curve([[-21, -36], [-20, 0], [-21, 37]]), 1.2]);
    P.push(['h', curve([[-28, 38], [-14, 36], [2, 31]]), 1]);
    return P;
  }

  // ---------- Мотоперчатки (glmo) ----------
  // Гладкая почти чёрная кожа ('darkleather', скин); жёсткая защита — серый пластик (свой материал 'gray!'): компактный
  // купол только над костяшками с одним широким бликом и 3 буграми на нём, по одной узкой пластине на средних фалангах,
  // слайдер на ладони задней перчатки. На тыле — кожаная панель с перфорацией и узкой светлой полосой 'bone', гармошка.
  // Запястье сужено ремешком с пряжкой; краги ~1/3 длины раструбом, срез открытого конца скруглён.
  const mArc = (v) => 91 + 0.08 * v - 0.004 * v * v;
  function moto() {
    const P = [], body = 'darkleather', light = 'bone', plast = 'gray!';
    const digit = (role, F, f, plate) => {
      P.push([role, digitPath(F, f.hb, f.ht), body]);
      if (plate) P.push(['p', padPath(F, F.s1 + 2, F.s2 - 1.5, f.hb * 0.5, f.ht * 0.48), plast]);
      knuck(F, f).forEach((q) => P.push(q));
    };
    // купол костяшек: кожаная подложка, один выпуклый купол, 3 бугра на нём (указательный+средний, безымянный, мизинец),
    // один широкий блик сверху-слева, мягкая тень на пальцы
    const shell = () => {
      const vs = [-40, -30, -20, -10, 0, 10, 20, 30, 41];
      const dm = (v) => 1 - (v / 42) * (v / 42);                     // купол: в середине глубже, к краям тоньше
      const top = vs.map((v) => [mArc(v) - 13 - 8 * dm(v), v]), bot = vs.map((v) => [mArc(v) + 3 + 3 * dm(v), v]).reverse();
      const pts = top.concat(bot);
      P.push(['d', curve(vs.slice(1, -1).map((v) => [mArc(v) + 10, v])), 4]);
      P.push(['q', blob(inset(pts, [mArc(0) - 6, 0], -2.4), 0.95), body]);
      P.push(['p', blob(pts, 0.95), plast]);
      [[20, 7, 13], [-8, 6, 8], [-27, 5.5, 7]].forEach((b) => {
        const v = b[0], u = mArc(v) - 3;
        P.push(['p', oval(u, v, b[1], b[2]), plast]);
      });
      P.push(['h', curve([[mArc(32) - 13, 32], [mArc(18) - 17, 18], [mArc(0) - 18, 0], [mArc(-18) - 15, -18]]), 2]);
      P.push(['d', curve(vs.slice(1, -1).map((v) => [mArc(v) + 4, v])), 1.2]);
    };
    // краги: раструб от суженного запястья к открытому концу (срез скруглён); stitch — строчка внутри контура
    const gaunt = (c) => [[6, -30 * c, 1], [8, 0], [6, 30 * c, 1], [-10, 35 * c], [-24, 41 * c], [-33, 46 * c],
      [-39.5, 45 * c], [-43.5, 34 * c], [-47, 12 * c], [-48, -12 * c], [-47, -36 * c], [-44, -46 * c], [-38.5, -48.5 * c],
      [-30, -44.5 * c], [-18, -39 * c], [-8, -33 * c]];
    const cuff = (role, c) => {
      const G = gaunt(c);
      P.push([role, blob(G, 0.9), body]);
      P.push(['e', curve(inset(G.slice(5, 13), [-18, 0], 5))]);
    };
    // ремешок поперёк запястья (сужение) с пряжкой на стороне большого пальца (v+) и липучкой рядом
    const strap = () => {
      P.push(['q', bandPath(-2, -15, 31.5, 36), body]);
      P.push(['e', curve([[-4, -29], [-3, 0], [-4, 30]]) + curve([[-13, -33], [-12, 0], [-13, 34]])]);
      P.push(['k', blob([[-4, -4, 1], [-4, 18, 1], [-13, 18, 1], [-13, -4, 1]], 0.4)]);
      P.push(['d', [-2, 4, 10, 16].map((v) => curve([[-5, v], [-12, v + 3]])).join(''), 0.8]);
      P.push(['q', blob([[-3, 33, 1], [-2, 47], [-9, 51], [-15, 47], [-14, 34, 1]], 0.7), body]);
      P.push(['l', blob([[1, 20, 1], [1, 42, 1], [-18, 42, 1], [-18, 20, 1]], 0.3) +
        blob([[-3, 24, 1], [-3, 38, 1], [-14, 38, 1], [-14, 24, 1]], 0.3)]);
      P.push(['m', poly([[-7.7, 25], [-7.7, 41], [-9.3, 41], [-9.3, 25]], true)]);
      P.push(['h', curve([[1, 41], [-8, 42], [-18, 41]]), 1]);
    };

    // --- задняя перчатка (левая): ладонью к нам, за передней; пальцы подогнуты; слайдер на ладони; контровой свет ---
    const c = 0.86;
    place([172, 108], 20, 1.36);
    cuff('q', c);
    P.push(['q', bandPath(-2, -15, 31.5 * c, 36 * c), body]);
    frames(0.7, -14, 1.5, c).forEach((F, i) => {
      if (i) P.push(gapShade(F, FING[i]));
      digit('q', F, FING[i], false);
    });
    P.push(['p', blob(PALM.map((q) => [q[0], q[1] * c].concat(q[2] ? [1] : []))), body]);
    P.push(['d', curve([[30, 24 * c], [52, 2], [80, -16 * c]]) + curve([[60, 34 * c], [80, 20 * c], [92, 4]]), 1.2]);
    P.push(['p', oval(22, -12 * c, 13, 10), plast]);
    P.push(['h', curve([[-44, -40 * c], [-20, -38 * c], [6, -29 * c], [28, -41 * c], [60, -47 * c], [86, -40 * c], [98, -22 * c]]), 2]);
    const RT = thumbFrame(0.9, -20, c);
    P.push(['q', digitPath(RT, THUMB.hb, THUMB.ht), body]);
    P.push(['d', crease(RT, RT.s1, THUMB.ht * 0.9, 2), 1.1]);
    P.push(['h', ridge(RT, THUMB.hb * 0.8, THUMB.ht * 0.76, 0.2, 0.85), 1.2]);

    // --- передняя перчатка (правая): тыльной стороной, пальцы согнуты ---
    place([84, 130], 27, 1.56);
    P.push(['d', curve([[56, 60], [80, 62], [98, 57]]), 7]);
    const T = thumbFrame(1, -16);
    P.push(['p', webPath(T, 1), body]);
    P.push(['p', digitPath(T, THUMB.hb, THUMB.ht), body]);
    P.push(['p', padPath(T, T.s1 - 6, T.s1 + 5, THUMB.hb * 0.56, THUMB.ht * 0.56), plast]);
    P.push(['d', crease(T, T.s2, THUMB.ht * 0.72, 1.4), 0.8]);
    P.push(['h', ridge(T, THUMB.hb * 0.8, THUMB.ht * 0.76, 0.2, 0.85), 1.2]);
    frames(1, -10).forEach((F, i) => {
      if (i) P.push(gapShade(F, FING[i]));
      digit('p', F, FING[i], true);
    });
    // тыл: кожаная панель с перфорацией, узкая светлая полоса по краю панели, гармошка над костяшками
    P.push(['p', blob(PALM), body]);
    P.push(['d', curve(T.pts([[T.L * 0.08, -THUMB.hb - 1], [T.L * 0.3, -THUMB.hb * 0.9]])), 1.4]);
    const bp = [[10, -25, 1], [mArc(-25) - 30, -25], [mArc(-8) - 30, -8], [mArc(10) - 30, 10], [mArc(26) - 30, 26, 1],
      [10, 26, 1], [8, 0]];
    P.push(['q', blob(bp, 0.9), body]);
    P.push(['e', blob(inset(bp, [34, 0], 2.4), 0.9)]);
    let dots = '';
    for (let u = 20; u < 58; u += 6) for (let v = -16; v <= 16; v += 6.5) dots += poly([[u, v + (u % 12 ? 3 : 0)], [u + 0.2, v + (u % 12 ? 3 : 0)]]);
    P.push(['d', dots, 1.7]);
    const bs = [[9, 27, 1], [mArc(27) - 30, 27, 1], [mArc(32) - 30, 32, 1], [9, 32, 1]];
    P.push(['p', blob(bs, 0.5), light]);
    [-28, -24, -20.5].forEach((du) => {
      const rv = [-32, -16, 0, 16, 34];
      P.push(['d', curve(rv.map((v) => [mArc(v) + du, v])), 1.2]);
    });
    P.push(['h', curve([[0, 30], [30, 39], [56, 42]]), 1.6]);
    P.push(['d', curve([[4, -26], [30, -33], [52, -38]]), 3]);
    shell();
    // краги: узкая косая светлая полоса, строчка по срезу, блик по освещённому краю
    cuff('p', 1);
    P.push(['q', blob([[-15, 34, 1], [-19.5, 36, 1], [-27.5, -38, 1], [-23, -36.5, 1]], 0.6), light]);
    P.push(['h', curve([[-8, 30], [-20, 35], [-32, 40]]), 1.3]);
    P.push(['d', curve([[-10, -28], [-24, -33], [-38, -38]]), 3]);
    strap();
    return P;
  }

  GEO.gltc = tactical();
  GEO.glmo = moto();
})();
