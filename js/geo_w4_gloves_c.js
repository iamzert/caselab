'use strict';

// Перчатки по рендерам CS2 (референсы пользователя tools/refs/73–84.png): glwr (обмотки), glsh (штурмовые — беспалые с шипами).
// Пара рисуется в поле 512×192; готовая картинка отражается по горизонтали (как всё оружие в игре).
// Загружается после js/geo_gloves*.js: GEO.<id> здесь заменяет прежнюю модель.
//
// Обе перчатки пары нарисованы явно одним списком деталей: задняя — первой и темнее (её окрашенные детали — роль q),
// поэтому скин идёт по паре одной плёнкой, а у задней видны свои пальцы и большой палец.
// Координаты пишем в «пространстве референса» — пикселях вырезки картинки CS2 в том виде, как она видна на экране
// (ближняя перчатка слева, пальцы вниз-вправо); mapper переводит их в поле и заранее отражает по x —
// рендерер (MIRROR) отразит картинку обратно, и в игре пара смотрит так же, как на референсе.
(function () {
  // Перевод пути из пространства референса в поле: x' = ox − k·x, y' = oy + k·y (только абсолютные M L C Q A Z)
  function mapper(k, ox, oy) {
    const fx = (x) => +(ox - k * x).toFixed(2), fy = (y) => +(oy + k * y).toFixed(2);
    function path(d) {
      const t = d.match(/[MLCQAZ]|-?\d*\.?\d+/gi) || [];
      let out = '', i = 0, cmd = '';
      while (i < t.length) {
        if (/[a-z]/i.test(t[i])) {
          cmd = t[i++].toUpperCase(); out += cmd;
          if (cmd === 'Z') out += ' ';
          continue;
        }
        if (cmd === 'A') {   // радиусы масштабируем, отражение меняет направление дуги
          out += (+t[i] * k).toFixed(2) + ',' + (+t[i + 1] * k).toFixed(2) + ' ' + (-t[i + 2]) + ' ' + t[i + 3] + ',' + (1 - t[i + 4]) +
            ' ' + fx(+t[i + 5]) + ',' + fy(+t[i + 6]) + ' ';
          i += 7;
        } else { out += fx(+t[i]) + ',' + fy(+t[i + 1]) + ' '; i += 2; }
      }
      return out;
    }
    return { path: path, x: fx, y: fy, k: k };
  }
  // Сборщик деталей: f — заливка (p/q с материалом, m l k g), ln — линия (d h s, толщина в единицах поля)
  function kit(mp) {
    const parts = [];
    return {
      parts: parts,
      f: (role, d, mat) => { parts.push(mat ? [role, mp.path(d), mat] : [role, mp.path(d)]); },
      ln: (role, d, w) => { parts.push([role, mp.path(d), w]); },
      e: (d) => { parts.push(['e', mp.path(d)]); },
      o: (x, y, r) => { parts.push(['o', mp.x(x), mp.y(y), +(r * mp.k).toFixed(2)]); },
    };
  }
  // Векторные мелочи (в пространстве референса)
  const pt = (p) => +p[0].toFixed(1) + ',' + +p[1].toFixed(1);
  const mv = (p, d, s) => [p[0] + d[0] * s, p[1] + d[1] * s];
  const dir = (a, b) => { const dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy); return [dx / l, dy / l]; };
  const norm = (v) => { const l = Math.hypot(v[0], v[1]); return [v[0] / l, v[1] / l]; };

  // Согнутый палец кулака — «шишка»: корень c на линии костяшек, u — вдоль линии, fd — куда смотрит палец,
  // w — ширина, len — вылет, rd — округлость кончика (0.5 — острее, 0.85 — круглее)
  function lobe(c, u, fd, w, len, rd) {
    const h = w / 2, r = rd || 0.7;
    const a = mv(mv(c, u, -h), fd, -9), b = mv(mv(c, u, h), fd, -9);
    const t = mv(c, fd, len);
    return 'M' + pt(a) + ' C' + pt(mv(a, fd, len * 0.85)) + ' ' + pt(mv(t, u, -h * r)) + ' ' + pt(t) +
      ' C' + pt(mv(t, u, h * r)) + ' ' + pt(mv(b, fd, len * 0.85)) + ' ' + pt(b) +
      ' C' + pt(mv(b, fd, -7)) + ' ' + pt(mv(a, fd, -7)) + ' ' + pt(a) + ' Z';
  }
  // Дуга поперёк пальца на доле q его вылета (сгиб сустава, кромка)
  function across(c, u, fd, w, len, q, bow) {
    const h = w / 2 * (1 - 0.45 * q * q), m = mv(c, fd, len * q);
    return 'M' + pt(mv(m, u, -h)) + ' Q' + pt(mv(m, fd, bow)) + ' ' + pt(mv(m, u, h));
  }

  // ---------- glwr «Обмотки» (Hand Wraps) ----------
  // Кулак, обмотанный бинтом: торец манжеты, витки на запястье, косой крест по тыльной стороне,
  // полоса через костяшки, заправленный хвост. Скин ложится на все слои бинта (глубокие слои — q, темнее);
  // пальцы и «шапка» костяшек под бинтом всегда своим материалом (sand!).
  // Пространство референса: вырезка 83@1375,712,390,262 («Кожа»).
  (function () {
    const K = kit(mapper(0.76, 409.1, -8.2));
    const { f, ln } = K;

    // Ряд согнутых пальцев: корни вдоль линии r1 → r0, fd — направление пальцев, lens — вылет каждого
    function fingers(r1, r0, fdRaw, w, lens, role) {
      const u = dir(r1, r0), fd = norm(fdRaw), L = Math.hypot(r0[0] - r1[0], r0[1] - r1[1]), step = L / lens.length;
      const cs = lens.map((_, i) => mv(r1, u, step * (i + 0.5)));
      cs.forEach((c, i) => f(role, lobe(c, u, fd, w, lens[i], 0.8), 'sand!'));
      cs.forEach((c, i) => {
        const len = lens[i];
        ln('d', across(c, u, fd, w, len, 0.64, 4), 0.7);                                         // сгиб сустава
        ln('d', across(c, u, fd, w * 0.8, len, 0.3, 3), 0.5);                                    // складка бинта
        if (i < lens.length - 1) {
          ln('d', 'M' + pt(mv(mv(c, u, w * 0.48), fd, 2)) + ' Q' + pt(mv(mv(c, u, w * 0.5), fd, len * 0.5)) +
            ' ' + pt(mv(mv(c, u, w * 0.36), fd, len * 0.92)), 1.1);                                 // щель между пальцами
        }
      });
      return { u: u, n: [u[1], -u[0]], cs: cs, w: w };
    }
    // Костяшки, проступающие под полосой бинта: блик-дуга над каждым корнем пальца
    function knuckles(F, back) {
      F.cs.forEach((c) => {
        const m = mv(c, F.n, -13);
        ln('h', 'M' + pt(mv(m, F.u, -F.w * 0.32)) + ' Q' + pt(mv(m, F.n, -6)) + ' ' + pt(mv(m, F.u, F.w * 0.32)), back ? 0.7 : 0.9);
        ln('d', 'M' + pt(mv(mv(m, F.u, F.w * 0.5), F.n, -2)) + ' L' + pt(mv(mv(m, F.u, F.w * 0.5), F.n, 9)), 0.6);
      });
    }

    // ===== Дальняя перчатка (справа на референсе): манжета с ярлыком, «шапка» костяшек, пальцы =====
    f('q', 'M214,66 C207,56 203,45 206,36 C222,24 246,15 272,16 C304,18 334,30 352,46 C366,60 374,80 378,100 ' +
      'L385,113 L271,195 L250,200 L232,170 Z', 'wrap');
    f('q', 'M300,22 C322,26 340,36 352,46 C366,60 374,80 378,100 L384,112 C352,108 318,112 290,124 C292,90 296,56 300,22 Z', 'sand!');
    const FB = fingers([380, 106], [266, 188], [0.35, 0.937], 40, [36, 42, 42, 38], 'q');
    // полоса бинта через костяшки
    f('q', 'M250,165 C288,138 326,111 364,83 C374,90 381,100 385,113 C346,141 308,168 271,195 C262,187 255,177 250,165 Z', 'wrap');
    // манжета-обмотка запястья
    f('q', 'M214,66 C207,56 203,45 206,36 C222,24 246,15 272,16 C286,17 298,20 308,24 C298,50 290,78 284,104 ' +
      'C272,124 256,146 240,160 Z', 'wrap');
    // ярлык на манжете
    f('p', 'M209,46 L228,41 L233,68 L214,73 Z', 'bone!');
    ln('d', 'M211,54 L230,49 M212,60 L231,55', 1.1);
    // кромки, блики и складки дальней перчатки
    ln('h', 'M210,37 C226,26 248,19 270,19', 1.1);
    ln('d', 'M308,24 C298,50 290,78 284,104', 1.0);
    ln('h', 'M314,26 C334,33 352,47 364,68', 1.2);
    ln('d', 'M322,44 C332,56 338,70 340,86 M306,64 C314,74 318,86 320,100', 0.6);
    ln('h', 'M252,163 C290,136 327,110 362,86', 1.0);
    ln('d', 'M271,195 C308,168 346,141 385,113', 1.0);
    knuckles(FB, true);

    // ===== Ближняя перчатка =====
    // глубокий слой бинта (виден в щелях между витками) и «шапка» костяшек (ткань перчатки)
    f('q', 'M78,27 C114,29 152,42 192,54 C218,61 238,68 250,82 C262,96 270,116 276,142 L146,227 ' +
      'C142,236 140,244 140,252 C92,218 44,168 18,132 C11,122 11,114 16,106 C34,82 58,50 78,27 Z', 'wrap');
    f('p', 'M150,42 C180,48 214,58 236,68 C252,78 264,96 270,116 C274,128 276,136 277,145 L236,150 C210,112 180,74 150,42 Z', 'sand!');
    const FF = fingers([272, 138], [140, 220], [0.24, 0.97], 45, [42, 50, 48, 42], 'p');
    // витки по тыльной стороне — косые полосы внахлёст, от верха запястья к костяшкам (как на референсе)
    f('p', 'M156,44 C190,63 228,89 263,116 L228,140 C193,114 160,92 127,68 C134,58 144,50 156,44 Z', 'wrap');
    f('p', 'M118,57 C156,79 193,105 228,135 L190,160 C158,139 127,116 96,93 Z', 'wrap');
    f('p', 'M98,90 C132,112 164,134 194,158 L154,182 C129,165 105,148 82,130 Z', 'wrap');
    f('q', 'M86,126 C112,143 136,159 158,176 L146,227 C142,236 140,244 140,252 C120,238 100,222 84,207 Z', 'wrap');
    // полоса через костяшки — над корнями пальцев
    f('p', 'M123,194 C168,168 214,140 257,113 C268,119 275,130 278,145 C234,174 190,203 146,229 C136,220 128,208 123,194 Z', 'wrap');
    // витки на запястье (внешний слой) с торцом и заправленным хвостом
    f('p', 'M78,27 C102,28 128,34 152,42 C128,70 110,110 106,148 C104,180 110,214 120,238 C92,218 44,168 18,132 ' +
      'C11,122 11,114 16,106 C34,82 58,50 78,27 Z', 'wrap');
    f('q', 'M24,140 C48,150 78,160 107,166 C106,192 111,218 120,238 C92,218 44,168 18,132 C19,135 21,138 24,140 Z', 'wrap');
    f('p', 'M78,27 C83,27 88,28 92,29 C72,52 48,84 31,108 C27,116 28,134 31,149 C26,144 22,138 18,132 ' +
      'C11,122 11,114 16,106 C34,82 58,50 78,27 Z', 'wrap');
    f('p', 'M40,152 C70,134 102,118 136,106 C141,116 144,127 146,138 C112,146 76,152 40,152 Z', 'wrap');

    // кромки витков (ступенька внахлёст) и светлый край ткани
    ln('d', 'M156,44 C190,63 228,89 263,116', 0.9);
    ln('d', 'M118,57 C156,79 193,105 228,135 M98,90 C132,112 164,134 194,158 M86,126 C112,143 136,159 158,176', 0.9);
    ln('h', 'M154,47 C188,66 226,92 260,118', 0.7);
    ln('h', 'M117,59 C155,81 192,107 226,137 M97,92 C131,114 163,136 192,160 M85,128 C111,145 135,161 156,178', 0.6);
    ln('d', 'M146,229 C190,203 234,174 278,145', 1.0);
    ln('h', 'M126,192 C170,166 214,139 255,116', 0.8);
    knuckles(FF, false);
    ln('d', 'M152,42 C128,70 110,110 106,148 C104,180 110,214 120,238', 1.1);
    ln('d', 'M120,34 C96,58 76,98 72,132 C70,160 74,186 84,205', 0.8);
    ln('h', 'M77,30 C58,52 35,84 19,107', 1.4);
    ln('d', 'M40,152 C76,152 112,146 146,138', 1.0);
    ln('h', 'M46,148 C73,133 103,120 133,110', 0.6);
    ln('d', 'M26,141 C50,151 79,161 107,167', 0.8);
    ln('h', 'M28,138 C52,148 80,157 106,163', 0.6);
    // складки ткани: короткие морщины поперёк витков и между костяшками
    ln('d', 'M138,82 C160,96 182,111 204,127 M118,112 C136,124 154,137 172,150', 0.55);
    ln('h', 'M139,79 C161,93 183,108 205,124 M119,109 C137,121 155,134 173,147', 0.5);
    ln('d', 'M180,64 C198,76 216,89 234,103', 0.5);
    ln('d', 'M186,207 C190,199 194,191 196,183 M220,187 C224,179 228,171 230,163 M154,225 C156,217 160,209 164,201', 0.7);
    ln('d', 'M86,72 C80,90 78,108 80,124', 0.6);
    // «шапка» костяшек: блик по краю
    ln('h', 'M236,70 C250,79 261,95 267,114', 1.0);

    GEO.glwr = K.parts;
  })();
})();
