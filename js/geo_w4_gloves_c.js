// =====================================================================================
// glsh «Штурмовые» — беспалые кожаные перчатки: пирамидальные шипы на костяшках и по краю тыльной накладки,
// эмблема — наш щит со скрещёнными клинками, манжета с сетчатой вставкой и ремешком на кнопке.
// Координаты — пиксели вырезки референса 84@40,175,380,255 (ближняя перчатка слева, пальцы вниз-вправо);
// tp() переводит их в поле с зеркалом по x, игра отражает картинку обратно — пара лежит как на рендере.
// Скин: корпус, тыльная накладка, пальцы, сетка. Свой материал ('…!'): манжета, кант, ремешок, края обрезов.
