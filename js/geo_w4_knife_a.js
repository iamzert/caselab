    const GH = [offs(EDGE1, GW[0] - 0.5, GW[1] - 1.6), offs(EDGE2, GW[1] - 1.6, GW[2] - 1.6), offs(EDGE3, GW[2] - 1.6, GW[3] - 1.6)];
