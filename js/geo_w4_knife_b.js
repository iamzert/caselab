  // ===================== 2. Штык-нож М9 (m9) =====================
  // Широкий клинок с вогнутым скосом, пила на обухе, прорезь кусачек, тёмная гарда с кольцом и длинным
  // нижним упором, круглая чёрная рукоять с рёбрами и насечкой, навершие с пазом и кнопкой.
