    const blade = Shape([163, SP]).L([386, SP]).S(CLIP).S(BELLY).L([163, ED]).Z();
    P.push(['p', blade.d + rr(390, 91, 19.5, 9.4, 4.7), 'steel']);
    // спуск к режущей кромке (своя грань — видна линия спуска)
    const bev = Shape([187, ED]).Q([187.6, 114.2], [197, 113.6]).L([380, 113.6])
      .S([[428, 108.6], [466, 99.6], [495, 91.6], TIP]).S(BELLY).L([187, ED]).Z();
    P.push(['p', bev.d, 'steel']);
