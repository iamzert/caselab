    P.push(['p', frame.d + holes, 'steel']);
    // спуск: одна линия параллельно кромке (~11 над ней, к острию сходит на нет)
    const edgePl = Shape([272, 126.6]).S(BOT.slice(0, -1).reverse().concat([TIP])).pl;   // кромка: от прилива к острию
    const gr = offs(edgePl, (t) => 11.4 * Math.pow(1 - t, 0.8), -1);
