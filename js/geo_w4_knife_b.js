    const bev = Shape(b0).Q([262, 118], gr[0]).L.apply(null, gr.slice(1)).d + ' L' + edgePl.slice().reverse().map(pt).join(' L') + ' L' + pt(b0) + ' Z';
    P.push(['p', bev, 'steel']);
    P.push(['d', line(offs(gr.slice(0, -6), 0.6, -1)), 0.5]);                            // граница спуска — тонкий шов
