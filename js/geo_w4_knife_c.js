    // упор под палец: выемка-рикассо у пятки кромки, лепесток, выемка под указательный палец, бугорок
    const TANG = [[232, 135.5, 1], [226, 141], [220.5, 133], [216.5, 121.5], [212, 113], [204, 105.4], [196, 102], [184, 101.5], [174, 106], [163, 112],
      [157, 116.6], [149, 116.6], [143, 112], [135, 111], [112, 112.2], [92, 116], [70, 121.4], [48, 127], [30, 131.4], [17, 133], [10.5, 129],
      [8.5, 120], [9.5, 104], [11.5, 90], [14, 80, 1]];
    const body = Pa([14, 80]).S(TOP).S(THROAT).S(BEAK).S(EDGE).S(TANG).Z();
