  // Гладкий контур через точки (сплайн Катмулла — Рома → кубические Безье); точка [x, y, 1] — острый угол
  function smooth(pts, closed) {
    const n = pts.length, P = (i) => (closed ? pts[(i + n) % n] : pts[Math.max(0, Math.min(n - 1, i))]);
    let d = 'M' + pt(pts[0]);
    for (let i = 0; i < (closed ? n : n - 1); i++) {
      const p0 = P(i - 1), p1 = P(i), p2 = P(i + 1), p3 = P(i + 2);
      const c1 = p1[2] ? p1 : [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
      const c2 = p2[2] ? p2 : [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
      d += ' C' + pt(c1) + ' ' + pt(c2) + ' ' + pt(p2);
    }
    return d + (closed ? ' Z ' : ' ');
  }
  // Планка Пикатинни сбоку: пазы прорезаны сверху (или снизу, если bot)
  function rail(x0, x1, y, h, step, gap, depth, bot) {
    const e = bot ? y + h : y, b = bot ? y : y + h, s = bot ? -1 : 1;
    let d = 'M' + F(x0) + ',' + F(b) + ' L' + F(x0) + ',' + F(e);
    for (let x = x0 + step - gap; x < x1 - gap - 1; x += step) {
      d += ' L' + F(x) + ',' + F(e) + ' L' + F(x) + ',' + F(e + s * depth) + ' L' + F(x + gap) + ',' + F(e + s * depth) + ' L' + F(x + gap) + ',' + F(e);
    }
    return d + ' L' + F(x1) + ',' + F(e) + ' L' + F(x1) + ',' + F(b) + ' Z ';
  }
  // Насечка: пазы (d) и блики на гребнях (h); lean — сдвиг верхнего конца штриха по x
  function serr(x0, x1, step, y0, y1, lean, w) {
    w = w || 1.1;
    let d = '', h = '';
    for (let x = x0; x <= x1 + 0.01; x += step) {
      d += 'M' + F(x) + ',' + F(y1) + ' L' + F(x + lean) + ',' + F(y0) + ' ';
      h += 'M' + F(x + w) + ',' + F(y1) + ' L' + F(x + lean + w) + ',' + F(y0) + ' ';
    }
    return [['d', d, w], ['h', h, F(w * 0.5)]];
  }
  // Рёбра по кромке: n выпуклых рёбер от (x0,y0) до (x1,y1); для кромки, идущей сверху вниз, — вперёд (+x)
  function ribs(x0, y0, x1, y1, n, amp) {
    const dx = (x1 - x0) / n, dy = (y1 - y0) / n, L = Math.hypot(dx, dy), nx = dy / L * amp * 2, ny = -dx / L * amp * 2;
    let d = '';
    for (let i = 0; i < n; i++) {
      const ax = x0 + dx * i, ay = y0 + dy * i;
      d += ' Q' + F(ax + dx / 2 + nx) + ',' + F(ay + dy / 2 + ny) + ' ' + F(ax + dx) + ',' + F(ay + dy);
    }
    return d;
  }
  // Канавки между рёбрами: короткие штрихи от кромки внутрь
  function ribLines(x0, y0, x1, y1, n, len) {
    const dx = (x1 - x0) / n, dy = (y1 - y0) / n, L = Math.hypot(dx, dy), nx = dy / L, ny = -dx / L;
    let d = '';
    for (let i = 1; i < n; i++) {
      const ax = x0 + dx * i, ay = y0 + dy * i;
      d += 'M' + F(ax - nx * 0.8) + ',' + F(ay - ny * 0.8) + ' L' + F(ax - nx * len) + ',' + F(ay - ny * len) + ' ';
    }
    return d;
  }
  // Штриховка выпуклого многоугольника линиями под углом deg с шагом step
  function hatch(poly, deg, step) {
    const a = deg * Math.PI / 180, ux = Math.cos(a), uy = Math.sin(a), nx = -uy, ny = ux;
    let lo = 1e9, hi = -1e9;
    poly.forEach((p) => { const t = p[0] * nx + p[1] * ny; lo = Math.min(lo, t); hi = Math.max(hi, t); });
    let d = '';
    for (let t = lo + step / 2; t < hi; t += step) {
      const hit = [];
      poly.forEach((p, i) => {
        const q = poly[(i + 1) % poly.length], ta = p[0] * nx + p[1] * ny - t, tb = q[0] * nx + q[1] * ny - t;
        if ((ta < 0) !== (tb < 0)) { const k = ta / (ta - tb); hit.push([p[0] + (q[0] - p[0]) * k, p[1] + (q[1] - p[1]) * k]); }
      });
      if (hit.length < 2) continue;
      hit.sort((u, v) => (u[0] * ux + u[1] * uy) - (v[0] * ux + v[1] * uy));
      d += 'M' + pt(hit[0]) + ' L' + pt(hit[hit.length - 1]) + ' ';
    }
    return d;
  }
