  // Перенос и масштаб пути (абсолютные команды M L C Q A H V Z): x' = x·s + dx, y' = y·s + dy
  function xpath(d, s, dx, dy) {
    let cmd = '', k = 0;
    return d.replace(/([A-Za-z])|(-?\d*\.?\d+(?:e-?\d+)?)/g, (m, c, n) => {
      if (c) { cmd = c.toUpperCase(); k = 0; return c; }
      const v = +n, i = k++;
      if (cmd === 'A') { const j = i % 7; return String(j < 2 ? F(v * s) : j < 5 ? v : F(v * s + (j === 5 ? dx : dy))); }
      if (cmd === 'H') return String(F(v * s + dx));
      if (cmd === 'V') return String(F(v * s + dy));
      return String(F(v * s + (i % 2 ? dy : dx)));
    });
  }
