  // Гладкая кривая через точки (Catmull-Rom → кубические Безье); продолжает путь, стоящий в pts[0]
  function sp(pts, k) {
    k = k == null ? 1 : k;
    let d = '';
    for (let i = 0; i < pts.length - 1; i++) {
      const a = pts[i - 1] || pts[i], b = pts[i], c = pts[i + 1], e = pts[i + 2] || pts[i + 1];
      d += ' C' + pt([b[0] + (c[0] - a[0]) * k / 6, b[1] + (c[1] - a[1]) * k / 6]) + ' ' +
        pt([c[0] - (e[0] - b[0]) * k / 6, c[1] - (e[1] - b[1]) * k / 6]) + ' ' + pt(c);
    }
    return d;
  }
