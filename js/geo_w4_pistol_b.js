  function inPoly(pg, x, y) {
    let c = false;
    for (let i = 0, j = pg.length - 1; i < pg.length; j = i++) {
      const a = pg[i], b = pg[j];
      if ((a[1] > y) !== (b[1] > y) && x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0]) c = !c;
    }
    return c;
  }
  // Штриховка многоугольника параллельными линиями под углом ang (рад) с шагом step; cut — отступ от краёв
  function hatch(pg, ang, step, cut) {
    const ux = Math.cos(ang), uy = Math.sin(ang), vx = -uy, vy = ux;
    const vs = pg.map((p) => p[0] * vx + p[1] * vy);
    const lo = Math.min.apply(null, vs), hi = Math.max.apply(null, vs);
    let d = '';
    for (let c = lo + step / 2; c < hi; c += step) {
      const ts = [];
      for (let i = 0; i < pg.length; i++) {
        const j = (i + 1) % pg.length, da = vs[i] - c, db = vs[j] - c;
        if ((da < 0) !== (db < 0)) {
          const t = da / (da - db);
          ts.push((pg[i][0] + (pg[j][0] - pg[i][0]) * t) * ux + (pg[i][1] + (pg[j][1] - pg[i][1]) * t) * uy);
        }
      }
      ts.sort((p, q) => p - q);
      for (let i = 0; i + 1 < ts.length; i += 2) {
        const t0 = ts[i] + (cut || 0), t1 = ts[i + 1] - (cut || 0);
        if (t1 - t0 < 1) continue;
        d += 'M' + pt([c * vx + t0 * ux, c * vy + t0 * uy]) + ' L' + pt([c * vx + t1 * ux, c * vy + t1 * uy]) + ' ';
      }
    }
    return d;
  }
  // Точечная насечка (пупырышки полимера): сетка со сдвигом рядов, отступ inset от края
  function stipple(pg, step, inset) {
    const xs = pg.map((p) => p[0]), ys = pg.map((p) => p[1]);
    const x0 = Math.min.apply(null, xs), x1 = Math.max.apply(null, xs), y0 = Math.min.apply(null, ys), y1 = Math.max.apply(null, ys);
    const ok = (x, y) => inPoly(pg, x, y) && inPoly(pg, x - inset, y) && inPoly(pg, x + inset, y) && inPoly(pg, x, y - inset) && inPoly(pg, x, y + inset);
    let d = '';
    for (let y = y0 + step / 2, row = 0; y < y1; y += step * 0.866, row++) {
      for (let x = x0 + (row % 2 ? step / 2 : 0); x < x1; x += step) {
        if (ok(x, y)) d += 'M' + r1(x) + ',' + r1(y) + ' L' + r1(x + 0.15) + ',' + r1(y) + ' ';
      }
    }
    return d;
  }
  // Точки вдоль отрезка A→B со смещением по внешней нормали (вперёд): prof = [[доля пути, смещение], ...]
  function strap(A, B, prof) {
    const dx = B[0] - A[0], dy = B[1] - A[1], L = Math.hypot(dx, dy), nx = dy / L, ny = -dx / L;
    return prof.map((q) => [A[0] + dx * q[0] + nx * q[1], A[1] + dy * q[0] + ny * q[1]]);
  }
