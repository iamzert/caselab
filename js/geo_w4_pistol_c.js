  // Многоугольник со скруглёнными углами: pts — [[x, y], ...], r — радиус (число или массив по вершинам)
  function rpoly(pts, r) {
    const n = pts.length;
    let d = '';
    for (let i = 0; i <= n; i++) {
      const v = pts[i % n], a = pts[(i + n - 1) % n], b = pts[(i + 1) % n];
      const ri = Array.isArray(r) ? r[i % n] : r;
      const la = Math.hypot(a[0] - v[0], a[1] - v[1]), lb = Math.hypot(b[0] - v[0], b[1] - v[1]);
      const k = Math.min(ri, la / 2, lb / 2);
      const p1 = [v[0] + (a[0] - v[0]) * k / la, v[1] + (a[1] - v[1]) * k / la];
      const p2 = [v[0] + (b[0] - v[0]) * k / lb, v[1] + (b[1] - v[1]) * k / lb];
      if (i === 0) d += 'M' + f(p2[0]) + ',' + f(p2[1]);
      else d += ' L' + f(p1[0]) + ',' + f(p1[1]) + ' Q' + f(v[0]) + ',' + f(v[1]) + ' ' + f(p2[0]) + ',' + f(p2[1]);
    }
    return d + ' Z ';
  }

  // Срезать углы многоугольника (вписанный многоугольник для штриховки скруглённых панелей)
  function chamfer(pts, r) {
    const n = pts.length, out = [];
    for (let i = 0; i < n; i++) {
      const v = pts[i], a = pts[(i + n - 1) % n], b = pts[(i + 1) % n];
      const la = Math.hypot(a[0] - v[0], a[1] - v[1]), lb = Math.hypot(b[0] - v[0], b[1] - v[1]);
      const k = Math.min(r, la / 2, lb / 2);
      out.push([v[0] + (a[0] - v[0]) * k / la, v[1] + (a[1] - v[1]) * k / la]);
      out.push([v[0] + (b[0] - v[0]) * k / lb, v[1] + (b[1] - v[1]) * k / lb]);
    }
    return out;
  }

