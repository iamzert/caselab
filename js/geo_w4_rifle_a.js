  // так внутренняя кромка дуги идёт строго параллельно внешней
  function offCubic(B, off, n, t0) {
    const a = B[0], b = B[1], c = B[2], e = B[3], out = [];
    for (let i = 0; i <= n; i++) {
      const t = t0 + (1 - t0) * i / n, u = 1 - t;
      const x = u * u * u * a[0] + 3 * u * u * t * b[0] + 3 * u * t * t * c[0] + t * t * t * e[0];
      const y = u * u * u * a[1] + 3 * u * u * t * b[1] + 3 * u * t * t * c[1] + t * t * t * e[1];
      const dx = u * u * (b[0] - a[0]) + 2 * u * t * (c[0] - b[0]) + t * t * (e[0] - c[0]);
      const dy = u * u * (b[1] - a[1]) + 2 * u * t * (c[1] - b[1]) + t * t * (e[1] - c[1]);
      const L = Math.hypot(dx, dy) || 1;
      out.push(r2(x - dy / L * off) + ',' + r2(y + dx / L * off));
    }
    return out;
  }

