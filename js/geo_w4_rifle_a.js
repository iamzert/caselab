  // Возвращает at(t, k): точка на доле длины t и доле ширины k (-0.5 — задняя кромка, 0.5 — передняя).
  function curvedMag(x0, y0, len, a0, a1, w0, w1, pw) {
    const N = 60, C = [];
    const ang = (t) => (a0 + (a1 - a0) * Math.pow(t, pw || 1)) * Math.PI / 180;
    let x = x0, y = y0;
    for (let i = 0; i <= N; i++) {
      const t = i / N;
      C.push([x, y, ang(t), w0 + (w1 - w0) * t]);
      const am = ang(Math.min(1, t + 0.5 / N));
      x += Math.sin(am) * len / N; y += Math.cos(am) * len / N;
    }
    return function (t, k) {
      const f = Math.max(0, Math.min(N, t * N)), i = Math.min(N - 1, Math.floor(f)), u = f - i;
      const A = C[i], B = C[i + 1];
      let cx = A[0] + (B[0] - A[0]) * u, cy = A[1] + (B[1] - A[1]) * u;
      const a = A[2] + (B[2] - A[2]) * u, w = A[3] + (B[3] - A[3]) * u;
      // за пределами 0..1 — продолжение по касательной (для крышек магазина)
      const ex = (t - Math.max(0, Math.min(1, t))) * len;
      cx += Math.sin(a) * ex; cy += Math.cos(a) * ex;
      return [cx + Math.cos(a) * w * k, cy - Math.sin(a) * w * k];
    };
  }
