  // Многоугольник со скруглёнными углами: вершины [x, y] или [x, y, r] (свой радиус у вершины)
  function rpoly(pts, r) {
    const n = pts.length;
    let d = '';
    for (let i = 0; i < n; i++) {
      const P = pts[i], A = pts[(i + n - 1) % n], B = pts[(i + 1) % n];
      const rad = P.length > 2 ? P[2] : r;
      const la = Math.hypot(A[0] - P[0], A[1] - P[1]), lb = Math.hypot(B[0] - P[0], B[1] - P[1]);
      const ka = Math.min(rad, la / 2) / la, kb = Math.min(rad, lb / 2) / lb;
      d += (i ? ' L' : 'M') + f(P[0] + (A[0] - P[0]) * ka) + ',' + f(P[1] + (A[1] - P[1]) * ka) +
        ' Q' + f(P[0]) + ',' + f(P[1]) + ' ' + f(P[0] + (B[0] - P[0]) * kb) + ',' + f(P[1] + (B[1] - P[1]) * kb);
    }
    return d + ' Z ';
  }

  // Параллельные штрихи под углом a (рад) с шагом step внутри выпуклого многоугольника, с отступом inset от краёв
  function hatch(pts, a, step, inset) {
    const dx = Math.cos(a), dy = Math.sin(a), nx = -dy, ny = dx;
    let lo = 1e9, hi = -1e9;
    pts.forEach((p) => { const s = p[0] * nx + p[1] * ny; lo = Math.min(lo, s); hi = Math.max(hi, s); });
    let d = '';
    for (let s = lo + step / 2; s < hi; s += step) {
      let t0 = 1e9, t1 = -1e9;
      for (let i = 0; i < pts.length; i++) {
        const A = pts[i], B = pts[(i + 1) % pts.length];
        const sa = A[0] * nx + A[1] * ny - s, sb = B[0] * nx + B[1] * ny - s;
        if ((sa < 0) !== (sb < 0)) {
          const k = sa / (sa - sb), x = A[0] + (B[0] - A[0]) * k, y = A[1] + (B[1] - A[1]) * k, t = x * dx + y * dy;
          t0 = Math.min(t0, t); t1 = Math.max(t1, t);
        }
      }
      if (t1 - t0 > 2 * inset + 1) {
        const a0 = t0 + inset, a1 = t1 - inset;
        d += 'M' + f(nx * s + dx * a0) + ',' + f(ny * s + dy * a0) + ' L' + f(nx * s + dx * a1) + ',' + f(ny * s + dy * a1) + ' ';
      }
    }
    return d;
  }

