  // Окружность из четырёх кубических дуг (её можно поворачивать вместе с группой)
  function ci(cx, cy, r) {
    const k = 0.5523 * r;
    return 'M' + pt(cx + r, cy) + ' C' + pt(cx + r, cy + k) + ' ' + pt(cx + k, cy + r) + ' ' + pt(cx, cy + r) +
      ' C' + pt(cx - k, cy + r) + ' ' + pt(cx - r, cy + k) + ' ' + pt(cx - r, cy) +
      ' C' + pt(cx - r, cy - k) + ' ' + pt(cx - k, cy - r) + ' ' + pt(cx, cy - r) +
      ' C' + pt(cx + k, cy - r) + ' ' + pt(cx + r, cy - k) + ' ' + pt(cx + r, cy) + ' Z ';
  }
  // Аффинное преобразование m = [a, b, c, d, e, f]: x' = a·x + c·y + e, y' = b·x + d·y + f
  const tp = (m, x, y) => [m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5]];
  // Применить m ко всем парам «x,y» пути (дуги A не используем — только M L C Q Z)
  const xf = (d, m) => d.replace(/(-?\d*\.?\d+),(-?\d*\.?\d+)/g, (s, x, y) => { const q = tp(m, +x, +y); return pt(q[0], q[1]); });
  // Поворот на deg градусов вокруг (cx, cy) и сдвиг на (dx, dy)
  function rotM(deg, cx, cy, dx, dy) {
    const c = Math.cos(rad(deg)), s = Math.sin(rad(deg));
    return [c, s, -s, c, cx - c * cx + s * cy + (dx || 0), cy - s * cx - c * cy + (dy || 0)];
  }
  // Штриховка выпуклого многоугольника линиями под углом a (рад) с шагом step
  function hatch(pg, step, a) {
    const ux = Math.cos(a), uy = Math.sin(a), nx = -uy, ny = ux;
    let s0 = Infinity, s1 = -Infinity, d = '';
    pg.forEach((q) => { const s = q[0] * nx + q[1] * ny; s0 = Math.min(s0, s); s1 = Math.max(s1, s); });
    for (let s = s0 + step / 2; s < s1; s += step) {
      const ts = [];
      for (let i = 0; i < pg.length; i++) {
        const A = pg[i], B = pg[(i + 1) % pg.length];
        const sa = A[0] * nx + A[1] * ny - s, sb = B[0] * nx + B[1] * ny - s;
        if ((sa <= 0 && sb > 0) || (sa > 0 && sb <= 0)) {
          const k = sa / (sa - sb);
          ts.push((A[0] + (B[0] - A[0]) * k) * ux + (A[1] + (B[1] - A[1]) * k) * uy);
        }
      }
      if (ts.length < 2) continue;
      const t0 = Math.min.apply(null, ts) + 0.4, t1 = Math.max.apply(null, ts) - 0.4;
      if (t1 - t0 < 1) continue;
      d += 'M' + pt(nx * s + ux * t0, ny * s + uy * t0) + ' L' + pt(nx * s + ux * t1, ny * s + uy * t1) + ' ';
    }
    return d;
  }
