  // Шаблон пути с округлением чисел: F`M${x},${y} L...`
  function F(s, ...v) {
    let d = s[0];
    v.forEach((x, i) => { d += (typeof x === 'number' ? Math.round(x * 100) / 100 : x) + s[i + 1]; });
    return d;
  }
  // Цилиндр вдоль X: x0..x1, ось на высоте y, радиус r0 сзади → r1 спереди; торцы чуть скруглены
  function tube(x0, x1, y, r0, r1) {
    if (r1 == null) r1 = r0;
    const a = Math.min(1.4, r0 * 0.3), b = Math.min(1.4, r1 * 0.3);
    return F`M${x0 + a},${y - r0} L${x1 - b},${y - r1} Q${x1},${y - r1} ${x1},${y - r1 + b} L${x1},${y + r1 - b} Q${x1},${y + r1} ${x1 - b},${y + r1} L${x0 + a},${y + r0} Q${x0},${y + r0} ${x0},${y + r0 - a} L${x0},${y - r0 + a} Q${x0},${y - r0} ${x0 + a},${y - r0} Z `;
  }
  // Стержень толщиной 2r от (x0, y0) до (x1, y1) со скруглёнными концами (ноги сошек, рычаги)
  function rod(x0, y0, x1, y1, r) {
    const L = Math.hypot(x1 - x0, y1 - y0), nx = -(y1 - y0) / L * r, ny = (x1 - x0) / L * r;
    return F`M${x0 + nx},${y0 + ny} L${x1 + nx},${y1 + ny} A${r},${r} 0 0,0 ${x1 - nx},${y1 - ny} L${x0 - nx},${y0 - ny} A${r},${r} 0 0,0 ${x0 + nx},${y0 + ny} Z `;
  }
  // Штриховка выпуклого многоугольника pts линиями под углом deg с шагом step (сетчатая насечка рукояток)
  function hatch(pts, deg, step) {
    const a = deg * Math.PI / 180, dx = Math.cos(a), dy = Math.sin(a), nx = -dy, ny = dx;
    let lo = 1e9, hi = -1e9, d = '';
    pts.forEach((p) => { const t = p[0] * nx + p[1] * ny; lo = Math.min(lo, t); hi = Math.max(hi, t); });
    for (let t = lo + step * 0.5; t < hi; t += step) {
      const cut = [];
      pts.forEach((p, i) => {
        const q = pts[(i + 1) % pts.length];
        const ta = p[0] * nx + p[1] * ny - t, tb = q[0] * nx + q[1] * ny - t;
        if ((ta < 0) !== (tb < 0)) { const k = ta / (ta - tb); cut.push([p[0] + (q[0] - p[0]) * k, p[1] + (q[1] - p[1]) * k]); }
      });
      if (cut.length < 2) continue;
      cut.sort((u, v) => (u[0] * dx + u[1] * dy) - (v[0] * dx + v[1] * dy));
      d += F`M${cut[0][0]},${cut[0][1]} L${cut[cut.length - 1][0]},${cut[cut.length - 1][1]} `;
    }
    return d;
  }
